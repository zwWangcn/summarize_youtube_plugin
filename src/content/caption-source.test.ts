import { describe, expect, it } from "vitest";
import { buildCaptionSourceWindow, fingerprintCaptionSource, locateSourceParts, prepareCaptionSource } from "./caption-source";
import type { Transcript } from "./transcript";

function transcript(text = "Hello world."): Transcript {
  return { languageCode: "en", isAutoGenerated: true, segments: [{ start: 0, duration: 3, text }] };
}

describe("immutable caption source coordinates", () => {
  it("normalizes without AI and remaps timing to the cleaned coordinates", () => {
    const input = transcript("  Hello   world. ");
    input.segments[0].timingMarkers = [{ offset: 10, start: 2 }];
    input.segments.unshift({ start: 0, duration: 0, text: " " });
    const prepared = prepareCaptionSource(input);
    expect(prepared.segments).toMatchObject([{ sourceStartId: 1, sourceEndId: 1, text: "Hello world.", timingMarkers: [{ offset: 6, start: 2 }] }]);
    expect(input.segments[1].text).toBe("  Hello   world. ");
  });
  it("excludes invalid times and does not manufacture markers for untimed spans", () => {
    const input = transcript();
    input.segments.push({ start: NaN, duration: 1, text: "bad" });
    const prepared = prepareCaptionSource(input);
    expect(prepared.segments).toHaveLength(1);
    expect([...buildCaptionSourceWindow(prepared).boundaries]).toEqual([[0, 0]]);
  });
  it("never uses markers in a word or outside a cue", () => {
    const input = transcript("unbelievable word");
    input.segments[0].timingMarkers = [
      { offset: 2, start: 1 }, { offset: 13, start: 2 },
      { offset: -1, start: 1 }, { offset: 100, start: 1 }, { offset: 13, start: 20 },
    ];
    expect([...buildCaptionSourceWindow(input).boundaries]).toEqual([[0, 0], [13, 2]]);
  });
  it("does not insert spaces between CJK events or before punctuation", () => {
    const input = transcript();
    input.segments = [{ start: 0, duration: 1, text: "你好" }, { start: 1, duration: 1, text: "世界" }, { start: 2, duration: 1, text: "。" }];
    expect(buildCaptionSourceWindow(input).text).toBe("你好世界。");
  });
  it("allows equivalent whitespace while preserving word separators and punctuation", () => {
    const window = buildCaptionSourceWindow(transcript("Hello world. Again."));
    expect(locateSourceParts(window, ["Hello world.", "Again."])).toEqual([[0, 12], [13, 19]]);
    expect(locateSourceParts(window, ["Hello  world.", "Again."])).toEqual([[0, 12], [13, 19]]);
    expect(() => locateSourceParts(window, ["Helloworld.", "Again."])).toThrow();
    expect(() => locateSourceParts(window, ["Hello world", "Again."])).toThrow();
  });
  it("changes the source fingerprint when content, timing or track identity changes", async () => {
    const base = transcript();
    const hash = await fingerprintCaptionSource(base);
    expect(hash).toMatch(/^[a-f0-9]{64}$/);
    expect(await fingerprintCaptionSource(structuredClone(base))).toBe(hash);
    const time = structuredClone(base); time.segments[0].start = 1;
    const text = transcript("Hello worlds.");
    const language = { ...base, languageCode: "fr" };
    for (const changed of [time, text, language, { ...base, isAutoGenerated: false }]) expect(await fingerprintCaptionSource(changed)).not.toBe(hash);
  });
  it("maps equivalent quote styles and composed Unicode back to original UTF-16 coordinates", () => {
    const text = '“Cafe\u0301” isn’t bad. Again.';
    const window = buildCaptionSourceWindow(transcript(text));
    const edge = text.indexOf("Again");
    const ranges = locateSourceParts(window, ['"Café" isn\'t bad.', 'Again.']);
    expect(ranges).toEqual([[0, edge - 1], [edge, text.length]]);
    expect(window.text.slice(...ranges[0])).toBe('“Cafe\u0301” isn’t bad.');
    const jamo = "한글";
    expect(locateSourceParts(buildCaptionSourceWindow(transcript(jamo)), ["한글"])).toEqual([[0, jamo.length]]);
  });
  it("tolerates optional CJK spacing, including spaces introduced between original events", () => {
    const tr = transcript();
    tr.segments = [{ start: 0, duration: 1, text: "你好。" }, { start: 1, duration: 1, text: "再见。" }];
    const window = buildCaptionSourceWindow(tr);
    expect(window.text).toBe("你好。 再见。");
    expect(locateSourceParts(window, ["你好。再见。"])).toEqual([[0, window.text.length]]);
    expect(locateSourceParts(window, ["你 好。", "再 见。"])).toEqual([[0, 3], [4, 7]]);
  });
  it.each(["Apart costs 1.5.", "A part costs 15.", "A part costs 1,5.", "A part costs 1.5!", "a part costs 1.5."])("still rejects changed words, numbers, punctuation and case: %s", (part) => {
    expect(() => locateSourceParts(buildCaptionSourceWindow(transcript("A part costs 1.5.")), [part])).toThrow();
  });
  it("never moves a cut into a surrogate pair or composed grapheme", () => {
    expect(() => locateSourceParts(buildCaptionSourceWindow(transcript("😀")), ["\ud83d", "\ude00"])).toThrow();
  });
});


describe("music-label preprocessing", () => {
  it("removes standalone music cues before building chunks, preserving source IDs and times", () => {
    const source: Transcript = { languageCode: "en", isAutoGenerated: true, segments: [
      { start: 0, duration: 10, text: "[music]" },
      { start: 10, duration: 2, text: "Hello." },
      { start: 12, duration: 4, text: " [MUSIC PLAYING] " },
      { start: 16, duration: 2, text: "Goodbye." },
    ] };
    expect(prepareCaptionSource(source).segments.map((cue) => [cue.sourceStartId, cue.text, cue.start, cue.duration]))
      .toEqual([[1, "Hello.", 10, 2], [3, "Goodbye.", 16, 2]]);
    expect(source.segments).toHaveLength(4);
  });

  it("removes inline labels and retains exact surviving word onsets and timing runs", () => {
    const text = "[Music] Looking almost [music] too good.";
    const words = ["[Music]", "Looking", "almost", "[music]", "too", "good."];
    let from = 0;
    const runs = words.map((word, index) => {
      const offset = text.indexOf(word, from); from = offset + word.length;
      return { offset, endOffset: offset + word.length, start: index };
    });
    const tr: Transcript = { languageCode: "en", isAutoGenerated: true, segments: [{
      text, start: 0, duration: 8, timingRuns: runs,
      timingMarkers: runs.map(({ offset, start }) => ({ offset, start })),
    }] };
    const [cue] = prepareCaptionSource(tr).segments;
    expect(cue.text).toBe("Looking almost too good.");
    expect(cue.timingMarkers).toEqual([
      { offset: 0, start: 1 }, { offset: 8, start: 2 }, { offset: 15, start: 4 }, { offset: 19, start: 5 },
    ]);
    expect(cue.timingRuns?.map((run) => [cue.text.slice(run.offset, run.endOffset), run.start]))
      .toEqual([["Looking", 1], ["almost", 2], ["too", 4], ["good.", 5]]);
    expect(buildCaptionSourceWindow({ ...tr, segments: [cue] }).boundaries.get(0)).toBe(1);
  });

  it("does not reinterpret a removed label onset as the later speech onset", () => {
    const tr = transcript("[music] Hello.");
    tr.segments[0].timingRuns = [{ offset: 0, endOffset: 14, start: 0 }];
    tr.segments[0].timingMarkers = [{ offset: 0, start: 0 }];
    const [cue] = prepareCaptionSource(tr).segments;
    expect(cue.text).toBe("Hello.");
    expect(cue.timingMarkers).toEqual([]);
    expect(cue.timingRuns).toEqual([{ offset: 0, endOffset: 6 }]);
  });

  it("filters music on uploaded tracks too, but retains spoken music and unrelated brackets", () => {
    const tr = transcript("[NASA] makes music. [Music theory] is a subject. [音乐]");
    tr.isAutoGenerated = false;
    expect(prepareCaptionSource(tr).segments[0].text).toBe("[NASA] makes music. [Music theory] is a subject.");
  });
});
