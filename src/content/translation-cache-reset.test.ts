import { getCachedTranslation, setCachedTranslationSection } from "../service/translation-cache";

const sourceTranscript = vi.fn(async (_preferredCaptionLanguage?: string) => ({
  languageCode: "en", isAutoGenerated: false,
  segments: [{ start: 0, duration: 4, text: "They have a private sector." }],
}));
const clearSourceCache = vi.fn();

const identity = {
  videoId: "video-1", sourceLanguage: "en", providerId: "deepseek",
  modelId: "deepseek-flash", targetLanguage: "zh-CN" as const, sourceFingerprint: "",
};
const translated = [{
  cueId: 0, chunkId: 0, sourceFrom: 0, sourceTo: 27, sourceText: "They have a private sector.",
  sourceStartId: 0, sourceEndId: 0, start: 0, duration: 4, text: "旧译文",
}];
const section = { chunkId: 0, targetStart: 0, targetEnd: 0, segments: translated };

function deferred<T>() {
  let resolve!: (value: T) => void;
  const promise = new Promise<T>((done) => { resolve = done; });
  return { promise, resolve };
}

async function flush() {
  // All external operations in this harness are explicitly controlled promises.
  for (let index = 0; index < 40; index++) await Promise.resolve();
}

describe("translation cache reset orchestration", () => {
  let store: Record<string, unknown>;
  let videoId: string;

  beforeEach(async () => {
    vi.useFakeTimers();
    vi.clearAllMocks();
    vi.mocked(translateTranscriptChunk).mockReset();
    vi.spyOn(console, "info").mockImplementation(() => {});
    vi.spyOn(console, "debug").mockImplementation(() => {});
    ui.root = false;
    ui.translations = {};
    ui.overlayText = "";
    ui.overlayStyle = null;
    store = {};
    videoId = "video-1";
    const location = { href: "https://www.youtube.com/watch?v=video-1" };
    vi.stubGlobal("window", { location, addEventListener: vi.fn() });
    vi.stubGlobal("MutationObserver", class { observe() {} disconnect() {} });
    vi.stubGlobal("requestAnimationFrame", vi.fn());
    vi.stubGlobal("document", Object.assign(new EventTarget(), {
      getElementById: (id: string) => id === "vas-root" && ui.root ? {} : null,
      querySelector: () => null, body: {},
      documentElement: { hasAttribute: () => false, classList: { contains: () => false } },
    }));
    vi.stubGlobal("chrome", {
      i18n: { getUILanguage: () => "en" },
      runtime: {
        sendMessage: vi.fn(async () => ({ providerId: "deepseek", providerName: "DeepSeek", hasKey: true })),
        onMessage: { addListener: vi.fn() },
      },
      storage: {
        onChanged: { addListener: vi.fn() },
        local: {
          get: vi.fn(async () => ({ ...store })),
          set: vi.fn(async (values) => { Object.assign(store, values); }),
          remove: vi.fn(async (keys: string | string[]) => {
            for (const key of Array.isArray(keys) ? keys : [keys]) delete store[key];
          }),
        },
      },
    });
    identity.sourceFingerprint = `${await fingerprintCaptionSource(prepareCaptionSource(await sourceTranscript()))}:balanced`;
    sourceTranscript.mockClear();
    await initContentScript({
      getTranscript: sourceTranscript,
      clearTranscriptCache: clearSourceCache,
      getVideoTitle: () => videoId, getVideoId: () => videoId, isOnVideoPage: () => true,
    }, { findInjectTarget: () => ({ matches: () => true, querySelector: () => null }) as unknown as HTMLElement });
  });

  afterEach(() => {
    vi.clearAllTimers();
    vi.useRealTimers();
    vi.unstubAllGlobals();
    vi.restoreAllMocks();
  });

  it("viewing source only never requests AI or translates the full video", async () => {
    await ui.callbacks!.onTranscript(true);
    expect(translateTranscriptChunk).not.toHaveBeenCalled();
    expect(chrome.storage.local.set).not.toHaveBeenCalled();
    expect(ui.translations).toEqual({});
  });

  it("preloads only the next block before playback reaches it and reuses it at the boundary", async () => {
    const events = new Map<string, () => void>();
    const video = { currentTime: 0, playbackRate: 1,
      addEventListener: (event: string, listener: () => void) => events.set(event, listener),
      removeEventListener: vi.fn(),
    };
    vi.stubGlobal("document", { ...document, querySelector: (selector: string) => selector === "video" ? video : null });
    sourceTranscript.mockResolvedValueOnce({ languageCode: "en", isAutoGenerated: false,
      segments: [0, 60, 120].map((start, index) => ({ start, duration: 60, text: `Caption ${index}.` })),
    });
    vi.mocked(translateTranscriptChunk).mockImplementation(async (transcript, chunk) =>
      alignTranslatedParts(transcript, chunk, [{ source: transcript.segments[chunk.targetStart].text, translation: `译文${chunk.id}` }]));
    await ui.callbacks!.onTranscript(true);
    ui.toggle!(true);
    await flush();
    expect(translateTranscriptChunk).toHaveBeenCalledTimes(1);

    video.currentTime = 29; events.get("timeupdate")!(); await flush();
    expect(translateTranscriptChunk).toHaveBeenCalledTimes(1);
    video.currentTime = 31;
    for (let tick = 0; tick < 10; tick++) events.get("timeupdate")!();
    await flush();
    expect(translateTranscriptChunk).toHaveBeenCalledTimes(2);
    expect(vi.mocked(translateTranscriptChunk).mock.calls[1][1].id).toBe(1);
    expect(vi.mocked(translateTranscriptChunk).mock.calls[0][4]?.aborted).toBe(false);
    expect(ui.translations[1].text).toBe("译文1");

    video.currentTime = 60; events.get("timeupdate")!(); await flush();
    expect(ui.overlayText).toBe("译文1");
    expect(translateTranscriptChunk).toHaveBeenCalledTimes(2);
    // A rate change triggers reconsideration immediately; at 2x, the 60 video seconds
    // until block 2 are only 30 real seconds. It is the single following block now.
    video.playbackRate = 2; events.get("ratechange")!(); await flush();
    expect(translateTranscriptChunk).toHaveBeenCalledTimes(3);
    expect(vi.mocked(translateTranscriptChunk).mock.calls[2][1].id).toBe(2);
  });

  it("cancels a speculative prefetch after seeking and prioritizes the newly active block", async () => {
    const events = new Map<string, () => void>();
    const video = { currentTime: 0, playbackRate: 1,
      addEventListener: (event: string, listener: () => void) => events.set(event, listener),
      removeEventListener: vi.fn(),
    };
    vi.stubGlobal("document", { ...document, querySelector: (selector: string) => selector === "video" ? video : null });
    sourceTranscript.mockResolvedValueOnce({ languageCode: "en", isAutoGenerated: false,
      segments: [0, 60, 120, 180].map((start, index) => ({ start, duration: 60, text: `Caption ${index}.` })),
    });
    vi.mocked(translateTranscriptChunk).mockImplementation(async (transcript, chunk, _lang, _progress, signal) => {
      if (chunk.id === 1) return new Promise((_resolve, reject) => {
        signal!.addEventListener("abort", () => reject(new DOMException("Aborted", "AbortError")), { once: true });
      });
      return alignTranslatedParts(transcript, chunk, [{ source: transcript.segments[chunk.targetStart].text, translation: `译文${chunk.id}` }]);
    });
    await ui.callbacks!.onTranscript(true);
    ui.toggle!(true); await flush();
    video.currentTime = 31; events.get("timeupdate")!(); await flush();
    const prefetch = vi.mocked(translateTranscriptChunk).mock.calls[1];
    expect(prefetch[1].id).toBe(1);
    expect(prefetch[4]?.aborted).toBe(false);

    video.currentTime = 185; events.get("seeking")!(); await flush();
    expect(prefetch[4]?.aborted).toBe(true);
    expect(vi.mocked(translateTranscriptChunk).mock.calls.map((request) => request[1].id)).toEqual([0, 1, 3]);
    expect(ui.overlayText).toBe("译文3");
    expect(ui.translations[1]).toBeUndefined();
    expect(ui.translations[2]).toBeUndefined();
  });

  it("translates only the requested stable block while keeping neighboring source as context", async () => {
    sourceTranscript.mockResolvedValueOnce({ languageCode: "en", isAutoGenerated: false, segments: [
      { start: 0, duration: 40, text: "One." }, { start: 40, duration: 40, text: "Two." },
    ] });
    await ui.callbacks!.onTranscript(true);
    const result = [{ ...translated[0], sourceText: "One.", sourceTo: 4, duration: 40, text: "一。" }];
    vi.mocked(translateTranscriptChunk).mockResolvedValueOnce(result);
    ui.callbacks!.onTranslateCurrent!(false);
    await flush();
    expect(translateTranscriptChunk).toHaveBeenCalledTimes(1);
    expect(vi.mocked(translateTranscriptChunk).mock.calls[0][1]).toMatchObject({
      id: 0, targetStart: 0, targetEnd: 0, contextStart: 0, contextEnd: 1,
    });
    expect(ui.translations[0].text).toBe("一。");
    expect(ui.translations[1]).toBeUndefined();
  });

  it("rejects a cached block whose source excerpts do not cover current source", async () => {
    await setCachedTranslationSection(identity, { ...section,
      segments: [{ ...translated[0], sourceText: "They have changed." }],
    });
    await ui.callbacks!.onTranscript(true);
    expect(ui.translations).toEqual({});
    expect(translateTranscriptChunk).not.toHaveBeenCalled();
  });

  it("does not restore results with a different source/timing fingerprint", async () => {
    await setCachedTranslationSection({ ...identity, sourceFingerprint: "different-source" }, section);
    await ui.callbacks!.onTranscript(true);
    expect(ui.translations).toEqual({});
  });

  it("ignores an old model response after changing the selected model", async () => {
    await ui.callbacks!.onTranscript(true);
    const response = deferred<TranslatedSegment[]>();
    vi.mocked(translateTranscriptChunk).mockReturnValueOnce(response.promise);
    ui.callbacks!.onTranslateCurrent!(false);
    await flush();
    const request = vi.mocked(translateTranscriptChunk).mock.calls[0];
    const listener = vi.mocked(chrome.storage.onChanged.addListener).mock.calls[0][0];
    listener({ model: { oldValue: "deepseek-flash", newValue: "another-model" } }, "sync");
    expect(request[4]?.aborted).toBe(true);
    response.resolve(translated);
    await flush();
    expect(ui.translations).toEqual({});
    expect(chrome.storage.local.set).not.toHaveBeenCalled();
  });

  it("invalidates the loaded transcript when source language preference changes", async () => {
    await ui.callbacks!.onTranscript(true);
    expect(sourceTranscript).toHaveBeenLastCalledWith("en");
    const listener = vi.mocked(chrome.storage.onChanged.addListener).mock.calls[0][0];
    listener({ preferredCaptionLanguage: { oldValue: "en", newValue: "ja" } }, "sync");
    await ui.callbacks!.onTranscript(true);
    expect(sourceTranscript).toHaveBeenLastCalledWith("ja");
    expect(sourceTranscript).toHaveBeenCalledTimes(2);
  });

  it("clears disk and memory, then allows a fresh translation", async () => {
    await setCachedTranslationSection(identity, section);
    await ui.callbacks!.onTranscript(true);
    expect(ui.translations[0].text).toBe("旧译文");

    ui.callbacks!.onClearTranslationCache!();
    await flush();
    expect(await getCachedTranslation(identity)).toBeNull();
    expect(ui.translations).toEqual({});
    expect(clearSourceCache).toHaveBeenCalledWith("video-1");
    expect(sourceTranscript).toHaveBeenCalledTimes(2);
    expect(ui.panel.setTranslationProgress).toHaveBeenCalledWith("translationCacheCleared");

    vi.mocked(translateTranscriptChunk).mockResolvedValueOnce([{ ...translated[0], text: "新译文" }]);
    ui.callbacks!.onTranslateCurrent!(false);
    await flush();
    expect(ui.translations[0].text).toBe("新译文");
    expect((await getCachedTranslation(identity))?.sections["0"].segments[0].text).toBe("新译文");
  });

  it("reports a refresh failure after clearing and does not reuse the old source", async () => {
    await ui.callbacks!.onTranscript(true);
    sourceTranscript.mockRejectedValueOnce(new Error("source unavailable"));
    ui.callbacks!.onClearTranslationCache!();
    await flush();
    expect(clearSourceCache).toHaveBeenCalledWith("video-1");
    expect(ui.panel.showError).toHaveBeenCalledWith("source unavailable");
    await ui.callbacks!.onTranscript(true);
    expect(sourceTranscript).toHaveBeenCalledTimes(3);
  });

  it("aborts an active request and ignores late output while clearing", async () => {
    await ui.callbacks!.onTranscript(true);
    const response = deferred<TranslatedSegment[]>();
    vi.mocked(translateTranscriptChunk).mockReturnValueOnce(response.promise);
    ui.callbacks!.onTranslateCurrent!(false);
    await flush();
    const args = vi.mocked(translateTranscriptChunk).mock.calls[0];

    ui.callbacks!.onClearTranslationCache!();
    expect(args[4]?.aborted).toBe(true);
    ui.callbacks!.onTranslateAll!(true);
    args[3]?.(translated, false);
    response.resolve(translated);
    await flush();

    expect(translateTranscriptChunk).toHaveBeenCalledTimes(1);
    expect(ui.translations).toEqual({});
    expect(await getCachedTranslation(identity)).toBeNull();
  });

  it("automatically retranslates enabled bilingual captions after clearing", async () => {
    await setCachedTranslationSection(identity, section);
    await ui.callbacks!.onTranscript(true);
    ui.toggle!(true);
    await flush();
    expect(ui.overlayText).toBe("旧译文");
    vi.mocked(translateTranscriptChunk).mockResolvedValueOnce([{ ...translated[0], text: "新的双语字幕" }]);

    ui.callbacks!.onClearTranslationCache!();
    await flush();

    expect(translateTranscriptChunk).toHaveBeenCalledTimes(1);
    expect(ui.overlayText).toBe("新的双语字幕");
    expect(ui.translations[0].text).toBe("新的双语字幕");
  });

  it("keeps a running translation and its timing when subtitle styling changes mid-stream", async () => {
    await ui.callbacks!.onTranscript(true);
    const response = deferred<TranslatedSegment[]>();
    vi.mocked(translateTranscriptChunk).mockReturnValueOnce(response.promise);
    ui.toggle!(true);
    await flush();
    const request = vi.mocked(translateTranscriptChunk).mock.calls[0];
    request[3]?.(translated, false);
    expect(ui.overlayText).toBe(""); // Uncommitted model output is never displayed.
    const onSettingsChange = vi.mocked(chrome.storage.onChanged.addListener).mock.calls[0][0];

    // Repeated slider updates arrive while the model is still streaming.
    for (const scale of [90, 110, 125]) {
      onSettingsChange({
        subtitleStyle: { newValue: {
          preset: "custom", translationFontScale: scale, backgroundOpacity: 45, maxWidth: 80,
        } },
      }, "sync");
      await flush();
      expect(request[4]?.aborted).toBe(false);
      expect(ui.overlayText).toBe("");
    }
    expect(ui.overlayStyle).toMatchObject({ translationFontScale: 125, maxWidth: 80 });

    const final = [{ ...translated[0], text: "他们有私营部门。" }];
    response.resolve(final);
    await flush();

    expect(translateTranscriptChunk).toHaveBeenCalledTimes(1);
    expect(ui.overlayText).toBe("他们有私营部门。");
    expect(ui.translations[0]).toEqual(final[0]);
    expect((await getCachedTranslation(identity))?.sections["0"].segments).toEqual(final);
  });

  it("does not restore an old cache read that completes after clearing", async () => {
    await setCachedTranslationSection(identity, section);
    const oldSnapshot = { ...store };
    const read = deferred<Record<string, unknown>>();
    vi.mocked(chrome.storage.local.get).mockImplementationOnce(async () => read.promise);
    const opening = ui.callbacks!.onTranscript(true);
    await flush();
    ui.callbacks!.onClearTranslationCache!();
    await flush();
    read.resolve(oldSnapshot);
    await opening;
    await ui.callbacks!.onTranscript(true);
    expect(ui.translations).toEqual({});
    expect(await getCachedTranslation(identity)).toBeNull();
  });

  it("waits for an already-started write so it cannot resurrect cleared translations", async () => {
    await ui.callbacks!.onTranscript(true);
    const write = deferred<void>();
    vi.mocked(chrome.storage.local.set).mockImplementationOnce(async (values) => {
      await write.promise;
      Object.assign(store, values);
    });
    vi.mocked(translateTranscriptChunk).mockResolvedValueOnce(translated);
    ui.callbacks!.onTranslateCurrent!(false);
    await flush();
    expect(chrome.storage.local.set).toHaveBeenCalledTimes(1);

    ui.callbacks!.onClearTranslationCache!();
    await flush();
    expect(chrome.storage.local.remove).not.toHaveBeenCalled();
    write.resolve();
    await flush();

    expect(await getCachedTranslation(identity)).toBeNull();
    expect(ui.translations).toEqual({});
  });

  it("reports removal failure and retains the cached translation", async () => {
    await setCachedTranslationSection(identity, section);
    await ui.callbacks!.onTranscript(true);
    vi.mocked(chrome.storage.local.remove).mockRejectedValueOnce(new Error("storage unavailable"));
    ui.callbacks!.onClearTranslationCache!();
    await flush();
    expect(ui.panel.showWarning).toHaveBeenCalledWith("translationCacheClearFailed");
    expect(ui.translations[0].text).toBe("旧译文");
    expect(await getCachedTranslation(identity)).not.toBeNull();
    expect(ui.panel.setTranslationCacheClearing).toHaveBeenLastCalledWith(false);
  });

  it("does not clear a new video's memory when navigating during removal", async () => {
    await setCachedTranslationSection(identity, section);
    await setCachedTranslationSection({ ...identity, videoId: "video-2" }, {
      ...section, segments: [{ ...translated[0], text: "第二个视频" }],
    });
    await ui.callbacks!.onTranscript(true);
    const removal = deferred<void>();
    vi.mocked(chrome.storage.local.remove).mockImplementationOnce(async (keys) => {
      await removal.promise;
      for (const key of Array.isArray(keys) ? keys : [keys]) delete store[key];
    });
    ui.callbacks!.onClearTranslationCache!();
    await flush();
    videoId = "video-2";
    // YouTube SPA navigation: URL changes, then the page fires yt-navigate-finish.
    window.location.href = "https://www.youtube.com/watch?v=video-2";
    document.dispatchEvent(new Event("yt-navigate-finish"));
    await ui.callbacks!.onTranscript(true);
    expect(ui.translations[0].text).toBe("第二个视频");
    removal.resolve();
    await flush();
    expect(ui.translations[0].text).toBe("第二个视频");
    expect(await getCachedTranslation({ ...identity, videoId: "video-2" })).not.toBeNull();
  });
});
