/**
 * YouTube 字幕提取器。
 *
 * 复用播放器字幕响应；无缓存时只通过播放器加载，不额外请求其他客户端或格式。
 */

import { UserError } from "../../utils/errors";
import { t } from "../../utils/i18n";
import { getCachedCaptionedText, parseJson3Captions } from "./caption-interceptor";
import type { Transcript, TranscriptSegment } from "../transcript";
import { loadPlayerCaptions } from "./player-captions";

// ---------------------------------------------------------------------------
// Language priority
// ---------------------------------------------------------------------------
const LANG_PRIORITY = ["ja", "en", "zh-Hans", "zh-HK", "zh-TW", "zh"];

// ---------------------------------------------------------------------------
// Extract ytInitialPlayerResponse from page
// ---------------------------------------------------------------------------
function currentUrlVideoId(): string {
  try {
    return new URL(window.location.href).searchParams.get("v") ?? "";
  } catch {
    return "";
  }
}

function playerResponseVideoId(response: Record<string, unknown>): string {
  const details = response.videoDetails as Record<string, unknown> | undefined;
  return typeof details?.videoId === "string" ? details.videoId : "";
}

export function selectPlayerResponseForVideo(
  responses: Record<string, unknown>[],
  expectedVideoId: string,
): Record<string, unknown> | null {
  return responses.find((response) => playerResponseVideoId(response) === expectedVideoId) ?? null;
}

function extractPlayerResponse(expectedVideoId: string): Record<string, unknown> | null {
  if (!expectedVideoId) return null;
  // Method 1: try window.ytInitialPlayerResponse
  const w = window as unknown as Record<string, unknown>;
  if (w.ytInitialPlayerResponse && typeof w.ytInitialPlayerResponse === "object") {
    const response = w.ytInitialPlayerResponse as Record<string, unknown>;
    const matched = selectPlayerResponseForVideo([response], expectedVideoId);
    if (matched) return matched;
  }

  // SPA 页面会保留旧 script；从最新的开始找，并且只接受当前 URL 的视频。
  const scripts = [...document.querySelectorAll("script")].reverse();
  for (const script of scripts) {
    const text = script.textContent ?? "";
    const match = text.match(/var\s+ytInitialPlayerResponse\s*=\s*(\{.+?\});/s);
    if (match) {
      try {
        const response = JSON.parse(match[1]) as Record<string, unknown>;
        const matched = selectPlayerResponseForVideo([response], expectedVideoId);
        if (matched) return matched;
      } catch {
        continue;
      }
    }
    // Also try window.ytInitialPlayerResponse = {...}
    const match2 = text.match(/ytInitialPlayerResponse\s*=\s*(\{.+?\});/s);
    if (match2) {
      try {
        const response = JSON.parse(match2[1]) as Record<string, unknown>;
        const matched = selectPlayerResponseForVideo([response], expectedVideoId);
        if (matched) return matched;
      } catch {
        continue;
      }
    }
  }
  return null;
}

export function parseTimedText(
  xml: string,
  languageCode: string = "unknown",
  isAutoGenerated: boolean = false,
): Transcript {
  const parser = new DOMParser();
  const doc = parser.parseFromString(xml, "text/xml");
  if (doc.querySelector("parsererror")) {
    return { languageCode, isAutoGenerated, segments: [] };
  }
  const texts = doc.querySelectorAll("text");
  const segments: TranscriptSegment[] = [];
  for (const el of texts) {
    const start = parseFloat(el.getAttribute("start") ?? "0");
    const dur = parseFloat(el.getAttribute("dur") ?? "0");
    if (!Number.isFinite(start) || start < 0 || !Number.isFinite(dur) || dur < 0) continue;
    // YouTube timedtext: content may be in child elements or raw text
    let content = "";
    for (const child of el.children) {
      content += child.textContent ?? "";
    }
    if (!content) {
      content = el.textContent ?? "";
    }
    content = decodeHtmlEntities(content.trim());
    if (content) {
      segments.push({ start, duration: dur, text: content });
    }
  }
  return { languageCode, isAutoGenerated, segments };
}

function decodeHtmlEntities(text: string): string {
  const txt = document.createElement("textarea");
  txt.innerHTML = text;
  return txt.value;
}

// ---------------------------------------------------------------------------
// Public API
// ---------------------------------------------------------------------------

const completedTranscripts = new Map<string, Transcript>();
const pendingTranscripts = new Map<string, Promise<Transcript>>();

/** 总结与双语字幕共享在途获取；失败后允许下一次重新请求。 */
export function getTranscript(): Promise<Transcript> {
  const videoId = getVideoIdFromUrl();
  if (!videoId) return Promise.reject(new UserError(t("errorNotYoutubeVideo"), "YT_NOT_VIDEO"));
  const pending = pendingTranscripts.get(videoId);
  if (pending) return pending;
  const cached = getCachedCaptionedText(videoId, LANG_PRIORITY) ?? completedTranscripts.get(videoId);
  if (cached) return Promise.resolve(cached);
  const request = loadTranscript(videoId).then((transcript) => {
    completedTranscripts.set(videoId, transcript);
    if (completedTranscripts.size > 5) {
      completedTranscripts.delete(completedTranscripts.keys().next().value!);
    }
    return transcript;
  }).finally(() => {
    if (pendingTranscripts.get(videoId) === request) pendingTranscripts.delete(videoId);
  });
  pendingTranscripts.set(videoId, request);
  return request;
}

async function loadTranscript(videoId: string): Promise<Transcript> {
  const assertCurrent = () => {
    if (getVideoIdFromUrl() !== videoId) throw new DOMException("Navigation changed", "AbortError");
  };

  // 1. 无等待快速路径：播放器恰好已经请求过字幕。
  const cached = getCachedCaptionedText(videoId, LANG_PRIORITY);
  if (cached) return cached;

  // Reuse the player's signed request and its in-flight response. Do not issue
  // separate ANDROID / JSON3 / XML probes before asking the player to load.
  const body = await loadPlayerCaptions(videoId, LANG_PRIORITY);
  assertCurrent();
  const url = new URL(body.url);
  const languageCode = url.searchParams.get("lang") || "unknown";
  const isAutoGenerated = url.searchParams.get("kind") === "asr";
  const transcript = parseJson3Captions(body.text, languageCode, isAutoGenerated) ??
    parseTimedText(body.text, languageCode, isAutoGenerated);
  if (!transcript.segments.length) {
    throw new UserError(t("errorYoutubeCaptionUnavailable"), "YT_EMPTY_CAPTIONS");
  }
  return transcript;
}

/** 从各种来源提取视频 ID。 */
export function getVideoIdFromUrl(): string {
  return currentUrlVideoId();
}

/** 获取当前页面的视频标题（含多重回退）。 */
export function getVideoTitle(): string {
  return extractTitle(extractPlayerResponse(currentUrlVideoId()));
}

/** 检测当前页面是否为 YouTube 视频页。 */
export function isYouTubeVideoPage(): boolean {
  return window.location.pathname === "/watch";
}

// ---------------------------------------------------------------------------
// Internal helpers (used by public API above)
// ---------------------------------------------------------------------------

function extractTitle(playerResponse: Record<string, unknown> | null): string {
  if (playerResponse) {
    const vd = playerResponse.videoDetails as Record<string, unknown> | undefined;
    const title = vd?.title as string | undefined;
    if (title) return title;
  }
  const dt = document.title || "";
  return dt.replace(/\s*-\s*YouTube\s*$/, "").trim() || t("unknownTitle");
}
