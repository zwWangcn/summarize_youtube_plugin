/**
 * YouTube 字幕提取器。
 *
 * 从页面中的 ytInitialPlayerResponse 提取字幕轨道信息，
 * 然后 fetch XML 字幕并解析为 [MM:SS] text 格式。
 */

import { UserError } from "../../utils/errors";
import { t } from "../../utils/i18n";
import { getCachedCaptionedText } from "./caption-interceptor";
import type { Transcript, TranscriptSegment } from "../transcript";

// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------
export interface CaptionTrack {
  baseUrl: string;
  name: { simpleText: string };
  vssId: string;
  languageCode: string;
  kind?: string;
}

export interface VideoInfo {
  title: string;
  videoId: string;
  captionTracks: CaptionTrack[];
}

// ---------------------------------------------------------------------------
// Language priority
// ---------------------------------------------------------------------------
const LANG_PRIORITY = ["ja", "en", "zh-Hans", "zh-HK", "zh-TW", "zh"];

// ---------------------------------------------------------------------------
// Extract ytInitialPlayerResponse from page
// ---------------------------------------------------------------------------
function currentUrlVideoId(): string {
  try {
    return new URL(window.location.href).searchParams.get("v") ?? "";
  } catch {
    return "";
  }
}

function playerResponseVideoId(response: Record<string, unknown>): string {
  const details = response.videoDetails as Record<string, unknown> | undefined;
  return typeof details?.videoId === "string" ? details.videoId : "";
}

export function selectPlayerResponseForVideo(
  responses: Record<string, unknown>[],
  expectedVideoId: string,
): Record<string, unknown> | null {
  return responses.find((response) => playerResponseVideoId(response) === expectedVideoId) ?? null;
}

function extractPlayerResponse(expectedVideoId: string): Record<string, unknown> | null {
  if (!expectedVideoId) return null;
  // Method 1: try window.ytInitialPlayerResponse
  const w = window as unknown as Record<string, unknown>;
  if (w.ytInitialPlayerResponse && typeof w.ytInitialPlayerResponse === "object") {
    const response = w.ytInitialPlayerResponse as Record<string, unknown>;
    const matched = selectPlayerResponseForVideo([response], expectedVideoId);
    if (matched) return matched;
  }

  // SPA 页面会保留旧 script；从最新的开始找，并且只接受当前 URL 的视频。
  const scripts = [...document.querySelectorAll("script")].reverse();
  for (const script of scripts) {
    const text = script.textContent ?? "";
    const match = text.match(/var\s+ytInitialPlayerResponse\s*=\s*(\{.+?\});/s);
    if (match) {
      try {
        const response = JSON.parse(match[1]) as Record<string, unknown>;
        const matched = selectPlayerResponseForVideo([response], expectedVideoId);
        if (matched) return matched;
      } catch {
        continue;
      }
    }
    // Also try window.ytInitialPlayerResponse = {...}
    const match2 = text.match(/ytInitialPlayerResponse\s*=\s*(\{.+?\});/s);
    if (match2) {
      try {
        const response = JSON.parse(match2[1]) as Record<string, unknown>;
        const matched = selectPlayerResponseForVideo([response], expectedVideoId);
        if (matched) return matched;
      } catch {
        continue;
      }
    }
  }
  return null;
}

// ---------------------------------------------------------------------------
// Parse captions
// ---------------------------------------------------------------------------
function parseCaptionTracks(playerResponse: Record<string, unknown>): CaptionTrack[] {
  const captions = playerResponse?.captions as Record<string, unknown> | undefined;
  const renderer = captions?.playerCaptionsTracklistRenderer as Record<string, unknown> | undefined;
  const tracks = (renderer?.captionTracks as CaptionTrack[]) ?? [];
  return tracks;
}

function pickCaptionTrack(tracks: CaptionTrack[]): CaptionTrack | null {
  if (!tracks.length) return null;

  const byLang = new Map<string, CaptionTrack>();
  for (const t of tracks) {
    if (t.baseUrl && !byLang.has(t.languageCode)) {
      byLang.set(t.languageCode, t);
    }
  }

  for (const lang of LANG_PRIORITY) {
    const match = byLang.get(lang);
    if (match) return match;
  }
  // Fallback: first track with a URL
  return tracks.find((t) => t.baseUrl) ?? null;
}

// ---------------------------------------------------------------------------
// Fetch and parse XML captions
// ---------------------------------------------------------------------------
async function fetchAndParseCaptions(
  baseUrl: string,
  languageCode: string,
  isAutoGenerated: boolean,
): Promise<Transcript> {
  let parsedUrl: URL;
  try {
    parsedUrl = new URL(baseUrl, "https://www.youtube.com");
  } catch {
    throw new UserError(t("errorYoutubeCaptionUnavailable"), "YT_INVALID_CAPTION_URL");
  }
  const isYouTubeHost = parsedUrl.hostname === "youtube.com" ||
    parsedUrl.hostname.endsWith(".youtube.com");
  if (parsedUrl.protocol !== "https:" || !isYouTubeHost) {
    throw new UserError(t("errorYoutubeCaptionUnavailable"), "YT_INVALID_CAPTION_URL");
  }
  // Strip "variant" parameter (e.g., variant=gemini) — it can cause empty
  // responses.  The variant key is NOT in sparams, so removing it does not
  // invalidate the URL signature.
  parsedUrl.searchParams.delete("variant");
  parsedUrl.searchParams.delete("fmt");

  const resp = await fetch(parsedUrl.toString());

  if (!resp.ok) {
    throw new UserError(
      t("errorYoutubeCaptionLoad"),
      "YT_CAPTION_FETCH",
      `HTTP ${resp.status}`,
    );
  }

  const xmlText = await resp.text();

  if (!xmlText || !xmlText.trim()) {
    throw new UserError(
      t("errorYoutubeCaptionUnavailable"),
      "YT_EMPTY_RESPONSE",
    );
  }

  const transcript = parseTimedText(xmlText, languageCode, isAutoGenerated);
  if (!transcript.segments.length) {
    throw new UserError(t("errorYoutubeCaptionUnavailable"), "YT_EMPTY_CAPTIONS");
  }
  return transcript;
}

export function parseTimedText(
  xml: string,
  languageCode: string = "unknown",
  isAutoGenerated: boolean = false,
): Transcript {
  const parser = new DOMParser();
  const doc = parser.parseFromString(xml, "text/xml");
  if (doc.querySelector("parsererror")) {
    return { languageCode, isAutoGenerated, segments: [] };
  }
  const texts = doc.querySelectorAll("text");
  const segments: TranscriptSegment[] = [];
  for (const el of texts) {
    const start = parseFloat(el.getAttribute("start") ?? "0");
    const dur = parseFloat(el.getAttribute("dur") ?? "0");
    if (!Number.isFinite(start) || start < 0 || !Number.isFinite(dur) || dur < 0) continue;
    // YouTube timedtext: content may be in child elements or raw text
    let content = "";
    for (const child of el.children) {
      content += child.textContent ?? "";
    }
    if (!content) {
      content = el.textContent ?? "";
    }
    content = decodeHtmlEntities(content.trim());
    if (content) {
      segments.push({ start, duration: dur, text: content });
    }
  }
  return { languageCode, isAutoGenerated, segments };
}

function decodeHtmlEntities(text: string): string {
  const txt = document.createElement("textarea");
  txt.innerHTML = text;
  return txt.value;
}

