/**
 * 提取 INNERTUBE_API_KEY。
 * 尝试多种方式，兼容 YouTube 页面不同的加载状态。
 */
function getApiKey(): string {
  // 方法 1：ytcfg.get()（页面正常加载时可用）
  try {
    const w = window as unknown as { ytcfg?: { get?: (key: string) => unknown; data_?: Record<string, unknown> } };
    const key = w.ytcfg?.get?.("INNERTUBE_API_KEY") as string | undefined;
    if (key) return key;
  } catch { /* continue */ }

  // 方法 2：ytcfg.data_（某些 YouTube 版本）
  try {
    const w = window as unknown as { ytcfg?: { data_?: Record<string, unknown> } };
    const key = w.ytcfg?.data_?.INNERTUBE_API_KEY as string | undefined;
    if (key) return key;
  } catch { /* continue */ }

  // 方法 3：正则提取页面 HTML（youtube-transcript-api 的做法，兼容性最强）
  try {
    const match = document.documentElement.outerHTML.match(
      /"INNERTUBE_API_KEY"\s*:\s*"([a-zA-Z0-9_-]+)"/
    );
    if (match?.[1]) return match[1];
  } catch { /* continue */ }

  return "";
}

/**
 * 通过 InnerTube ANDROID 客户端获取字幕 —— 参考 youtube-transcript-api 方案。
 *
 * YouTube WEB 客户端的 timedtext 请求需要 POT (Proof of Origin Token)，
 * 但 ANDROID 客户端不受此限制。此方法：
 *   1. POST youtubei/v1/player（ANDROID 上下文）→ 获取带有效签名的 baseUrl
 *   2. GET baseUrl → 返回 XML timedtext → 解析
 *
 * 这是目前最可靠的静默字幕获取方式，无需 CC 按钮、拦截器或播放器操作。
 */
async function fetchCaptionsViaInnerTube(
  videoId: string,
): Promise<Transcript> {
  const apiKey = getApiKey();
  if (!apiKey || !videoId) throw new UserError(t("errorPageNotReady"), "YT_NO_API_KEY");

  const resp = await fetch(
    `https://www.youtube.com/youtubei/v1/player?key=${apiKey}`,
    {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        "Accept-Language": "en-US",
      },
      body: JSON.stringify({
        context: {
          client: {
            clientName: "ANDROID",
            clientVersion: "20.10.38",
          },
        },
        videoId,
      }),
    },
  );

  if (!resp.ok) throw new UserError(t("errorCaptionService"), "YT_INNERTUBE", `HTTP ${resp.status}`);
  const data = await resp.json();

  const tracks =
    (data?.captions?.playerCaptionsTracklistRenderer
      ?.captionTracks as CaptionTrack[]) ?? [];

  if (!tracks.length) throw new UserError(t("errorNoCaptions"), "YT_NO_CAPTIONS");

  const track = pickCaptionTrack(tracks);
  if (!track) {
    const available = tracks.map((t) => t.languageCode).join(", ");
    throw new UserError(t("errorNoPreferredYoutubeCaptions"), "YT_NO_PREF_LANG", `available: ${available}`);
  }
  return fetchAndParseCaptions(track.baseUrl, track.languageCode, track.kind === "asr");
}

/** 获取当前页面的视频字幕文本。 */
export async function getTranscript(): Promise<Transcript> {
  const videoId = getVideoIdFromUrl();
  if (!videoId) throw new UserError(t("errorNotYoutubeVideo"), "YT_NOT_VIDEO");

  // 1. 无等待快速路径：播放器恰好已经请求过字幕。
  const cached = getCachedCaptionedText(videoId, LANG_PRIORITY);
  if (cached) return cached;

  // 2. 主路径：InnerTube ANDROID（最可靠，静默）
  try {
    const transcript = await fetchCaptionsViaInnerTube(videoId);
    if (getVideoIdFromUrl() !== videoId) throw new DOMException("Navigation changed", "AbortError");
    return transcript;
  } catch (e) {
    if ((e as Error)?.name === "AbortError") throw e;
    console.debug("[vas] InnerTube 失败，回退到直接 fetch:", e instanceof Error ? e.message : String(e));
  }

  // 3. 最终回退：直接 fetch ytInitialPlayerResponse 中的 baseUrl
  const info = getVideoInfo();
  if (!info) throw new UserError(t("errorNotYoutubeVideo"), "YT_NOT_VIDEO");
  if (!info.captionTracks.length) throw new UserError(t("errorNoCaptions"), "YT_NO_CAPTIONS");

  const track = pickCaptionTrack(info.captionTracks);
  if (!track) {
    const available = info.captionTracks.map((t) => t.languageCode).join(", ");
    throw new UserError(t("errorNoPreferredYoutubeCaptions"), "YT_NO_PREF_LANG", `available: ${available}`);
  }

  const transcript = await fetchAndParseCaptions(track.baseUrl, track.languageCode, track.kind === "asr");
  if (getVideoIdFromUrl() !== videoId) throw new DOMException("Navigation changed", "AbortError");
  return transcript;
}

/** 从当前 YouTube 页面提取视频信息（标题 + 字幕轨道）。 */
function getVideoInfo(): VideoInfo | null {
  const videoId = getVideoIdFromUrl();
  const playerResponse = extractPlayerResponse(videoId);
  if (!playerResponse) return null;

  const title = extractTitle(playerResponse);
  const captionTracks = parseCaptionTracks(playerResponse);

  return { title, videoId, captionTracks };
}

/** 从各种来源提取视频 ID。 */
export function getVideoIdFromUrl(): string {
  return currentUrlVideoId();
}

/** 获取当前页面的视频标题（含多重回退）。 */
export function getVideoTitle(): string {
  return extractTitle(extractPlayerResponse(currentUrlVideoId()));
}

/** 检测当前页面是否为 YouTube 视频页。 */
export function isYouTubeVideoPage(): boolean {
  return window.location.pathname === "/watch";
}

// ---------------------------------------------------------------------------
// Internal helpers (used by public API above)
// ---------------------------------------------------------------------------

function extractTitle(playerResponse: Record<string, unknown> | null): string {
  if (playerResponse) {
    const vd = playerResponse.videoDetails as Record<string, unknown> | undefined;
    const title = vd?.title as string | undefined;
    if (title) return title;
  }
  const dt = document.title || "";
  return dt.replace(/\s*-\s*YouTube\s*$/, "").trim() || t("unknownTitle");
}
