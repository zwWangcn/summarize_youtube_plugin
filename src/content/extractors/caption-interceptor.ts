/**
 * 字幕拦截器。
 *
 * 内容脚本运行在 ISOLATED world（以正常加载 CRXJS bundle），
 * manifest 在 document_start 将独立脚本注入 MAIN world，
 * 本模块负责解析捕获的字幕；轨道选择和缓存统一在 MAIN world 完成。
 *
 * 主世界的拦截器通过 DOM CustomEvent 把捕获的字幕数据传回内容脚本。
 *
 * 主动获取复用 MAIN world 播放器请求。
 */

import type {
  Transcript,
  TranscriptSegment,
} from "../transcript";
import { normalizeCaptionRuns } from "../caption-text";

export function parseJson3Captions(
  raw: string,
  languageCode: string = "unknown",
  isAutoGenerated: boolean = true,
): Transcript | null {
  let data: Record<string, unknown>;
  try { data = JSON.parse(raw); } catch { return null; }

  const events = data?.events;
  if (!events || !Array.isArray(events)) return null;

  const segments: TranscriptSegment[] = [];
  for (const ev of events as Array<Record<string, unknown>>) {
    if (!Array.isArray(ev.segs)) continue;
    const startMs = Number(ev.tStartMs);
    const durationMs = Number(ev.dDurationMs);
    if (!Number.isFinite(startMs) || startMs < 0 || !Number.isFinite(durationMs) || durationMs < 0) {
      continue;
    }
    const runs = (ev.segs as unknown[]).map((seg) => {
      const value = seg && typeof seg === "object" ? seg as Record<string, unknown> : {};
      const offsetMs = value.tOffsetMs;
      return {
        text: typeof value.utf8 === "string" ? value.utf8 : "",
        ...(typeof offsetMs === "number" && Number.isFinite(offsetMs) && offsetMs >= 0
          ? { start: (startMs + offsetMs) / 1000 }
          : {}),
      };
    });
    const { text, timingMarkers, timingRuns } = normalizeCaptionRuns(runs);
    if (text) {
      segments.push({
        start: startMs / 1000,
        duration: durationMs / 1000,
        text,
        ...(timingMarkers.length ? { timingMarkers, timingRuns } : {}),
      });
    }
  }
  if (!segments.length) return null;
  return { languageCode, isAutoGenerated, segments };
}

/** YouTube's `tlang` response contains translated text and must never become our source track. */
export function isTranslatedCaptionURL(url: string): boolean {
  try { return new URL(url).searchParams.has("tlang"); }
  catch { return /[?&]tlang=/.test(url); }
}
