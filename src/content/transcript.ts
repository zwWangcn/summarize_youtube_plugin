import { formatTime } from "../utils/text";
import type { OutputLanguage } from "../utils/i18n";
import { segmentTranscriptSemantically } from "./semantic-segmentation";

export type TranscriptSplitReason =
  | "start-of-transcript"
  | "terminal-punctuation"
  | "long-pause"
  | "sentence-boundary-model"
  | "clause-boundary"
  | "sound-label"
  | "weak-punctuation"
  | "speaker-change"
  | "forced-best-candidate"
  | "end-of-transcript";

export interface TranscriptSegment {
  start: number;
  duration: number;
  text: string;
  /** Exact word/run starts from YouTube JSON3, indexed into normalized `text`. */
  timingMarkers?: TranscriptTimingMarker[];
  /** Inclusive indexes of the original YouTube caption events covered by this cue. */
  sourceStartId?: number;
  sourceEndId?: number;
  /** Why the semantic unit ends here; retained for bad-boundary diagnostics. */
  splitReason?: TranscriptSplitReason;
  /** Local candidate score before path-wide length/duration penalties. */
  splitScore?: number;
}

export interface TranscriptTimingMarker {
  offset: number;
  start: number;
}

export interface Transcript {
  languageCode: string;
  isAutoGenerated: boolean;
  segments: TranscriptSegment[];
}

/**
 * Build complete semantic translation units, then map them to immutable YouTube timing.
 * Player lookup and rendering consume the result but never decide sentence boundaries.
 */
export function buildAlignedTranscript(transcript: Transcript): Promise<Transcript> {
  return segmentTranscriptSemantically(transcript);
}

/** Locate the cue active at the given playback time. */
export function findActiveCueIndex(segments: TranscriptSegment[], time: number): number {
  let low = 0;
  let high = segments.length - 1;
  let candidate = -1;
  while (low <= high) {
    const middle = Math.floor((low + high) / 2);
    if (segments[middle].start <= time) {
      candidate = middle;
      low = middle + 1;
    } else {
      high = middle - 1;
    }
  }
  if (candidate < 0) return -1;
  const cue = segments[candidate];
  return time < cue.start + cue.duration ? candidate : -1;
}

export interface CaptionPrefetchRange {
  start: number;
  end: number;
}

/** Calculate the next missing cue window without introducing playback side effects. */
export function getCaptionPrefetchRange(
  segments: TranscriptSegment[],
  currentCueId: number,
  currentTime: number,
  hasTranslation: (cueId: number) => boolean,
  minimumBufferSeconds: number = 15,
  windowSeconds: number = 60,
): CaptionPrefetchRange | null {
  let firstMissing = currentCueId;
  while (firstMissing < segments.length && hasTranslation(firstMissing)) firstMissing += 1;
  if (firstMissing >= segments.length) return null;
  const bufferedEnd = firstMissing > currentCueId
    ? segments[firstMissing - 1].start + segments[firstMissing - 1].duration
    : segments[currentCueId]?.start ?? currentTime;
  if (firstMissing > currentCueId && bufferedEnd - currentTime >= minimumBufferSeconds) {
    return null;
  }

  const startTime = segments[firstMissing].start;
  let end = firstMissing;
  while (end + 1 < segments.length && segments[end + 1].start < startTime + windowSeconds) {
    end += 1;
  }
  return { start: firstMissing, end };
}

export function transcriptToText(transcript: Transcript): string {
  return transcript.segments
    .filter((segment) => segment.text.trim())
    .map((segment) => `${formatTime(segment.start)}\n${segment.text.trim()}`)
    .join("\n");
}

export function isTranscriptInOutputLanguage(
  languageCode: string,
  outputLanguage: OutputLanguage,
): boolean {
  const normalized = languageCode.trim().toLowerCase().replaceAll("_", "-");
  if (outputLanguage === "zh-CN") {
    return normalized === "zh" || /^zh-(cn|sg|hans)(?:-|$)/.test(normalized);
  }
  if (outputLanguage === "zh-TW") {
    return /^zh-(tw|hk|mo|hant)(?:-|$)/.test(normalized);
  }
  return normalized === outputLanguage || normalized.startsWith(`${outputLanguage}-`);
}
