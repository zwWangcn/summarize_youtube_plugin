import { describe, expect, it } from "vitest";
import { buildAlignedTranscript, findActiveCueIndex, type Transcript } from "./transcript";
import { parseJson3Captions } from "./extractors/caption-interceptor";

const examples = {
  souls: "And I wouldn't call this game a Souls-like game based on the mechanics that it has, but it has like a focus on Chinese martial arts and kung fu when you're fighting enemies and things like that.",
  phantom: "So, if you're not familiar with Phantom Blade Zero, since I haven't done a video on it in a while, Phantom Blade Zero is an action RPG that's being developed by S-Game, which is a studio based in China.",
  currency: "Um and why this is really impactful on the gameplay and exploration is that the currency you gain from defeating enemies that you're going to use to unlock more skills and to upgrade your weapons is finite.",
  respec: "Um and something that I really like that should probably go in the pros column of the first pro really is that you can respec your character and you can get all your materials and currency back from upgrading weapons for free at any time you want.",
};

function transcript(text: string, languageCode = "en"): Transcript {
  return { languageCode, isAutoGenerated: true, segments: [{ start: 0, duration: 10, text }] };
}

function timedWords(words: string[], pauseAfter?: number): Transcript {
  let offsetMs = 0;
  const segs = words.map((word, index) => {
    const run = { utf8: `${word}${index + 1 < words.length ? " " : ""}`, tOffsetMs: offsetMs };
    offsetMs += index === pauseAfter ? 1000 : 200;
    return run;
  });
  return parseJson3Captions(JSON.stringify({ events: [{
    tStartMs: 100_000, dDurationMs: offsetMs, segs,
  }] }), "en")!;
}

describe("semantic segmentation quality", () => {
  it.each([examples.souls, examples.phantom])("prefers a clause-ending comma without knowing names", async (text) => {
    const aligned = await buildAlignedTranscript(transcript(text));
    const offset = text === examples.souls ? text.indexOf("but it") : text.lastIndexOf("Phantom Blade");
    expect(aligned.segments.map((segment) => segment.text)).toEqual([
      text.slice(0, offset).trim(), text.slice(offset),
    ]);
    expect(aligned.segments[0].splitDiagnostics?.grammarPenalty).toBe(0);
  });

  it("recognizes an unknown modal verb's object and the following coordinate clause", async () => {
    const aligned = await buildAlignedTranscript(transcript(examples.respec));
    const offset = examples.respec.indexOf("and you can get");
    expect(aligned.segments.map((segment) => segment.text)).toEqual([
      examples.respec.slice(0, offset).trim(), examples.respec.slice(offset),
    ]);
    const inventedVerb = examples.respec.replace("respec", "florp");
    const invented = await buildAlignedTranscript(transcript(inventedVerb));
    expect(invented.segments[0].text).toContain("florp your character");
  });

  it("does not move a bad boundary into another part of the same modifying phrase", async () => {
    const aligned = await buildAlignedTranscript(transcript(examples.currency));
    expect(aligned.segments.map((segment) => segment.text).join(" ")).toBe(examples.currency);
    expect(aligned.segments.slice(0, -1).every(({ text }) => !/\b(?:gain|defeating)$/u.test(text))).toBe(true);
    expect(aligned.segments.some(({ text }) => text.includes("gain from defeating enemies"))).toBe(true);
  });

  it.each([
    "We tried, but the same sentence continued.",
    "We packed water, food, batteries, and a map.",
    "So, we waited a while, but it worked.",
  ])("keeps a short sentence intact: %s", async (text) => {
    const aligned = await buildAlignedTranscript(transcript(text));
    expect(aligned.segments.map((segment) => segment.text)).toEqual([text]);
  });

  it("uses a word-level timing outlier to prefer an uneven but feasible split", async () => {
    const words = Array(40).fill("word");
    const smooth = await buildAlignedTranscript(timedWords(words));
    const source = timedWords(words, 23);
    const aligned = await buildAlignedTranscript(source);
    expect(aligned.segments).toHaveLength(2);
    expect(aligned.segments[0].text.split(" ")).toHaveLength(24);
    expect(aligned.segments[0].text).not.toBe(smooth.segments[0].text);
    expect(aligned.segments[0].splitDiagnostics?.timeBonus).toBe(2);
    expect(aligned.segments[0].splitReason).toBe("timing-gap");
    const cutTime = source.segments[0].timingRuns![24].start!;
    expect(aligned.segments[1].start).toBe(cutTime);
    expect(aligned.segments[0].start + aligned.segments[0].duration).toBeCloseTo(cutTime);
    expect(findActiveCueIndex(aligned.segments, cutTime - 0.01)).toBe(0);
    expect(findActiveCueIndex(aligned.segments, cutTime)).toBe(1);
    expect(aligned.segments.map((segment) => segment.text).join(" ")).toBe(source.segments[0].text);
  });

  it("does not let timing alone break a determiner from its noun", async () => {
    const words = Array(40).fill("word");
    words[19] = "your";
    words[20] = "character";
    const aligned = await buildAlignedTranscript(timedWords(words, 19));
    expect(aligned.segments.some(({ text }) => text.includes("your character"))).toBe(true);
  });

  it("does not apply English function-word rules to another language", async () => {
    const aligned = await buildAlignedTranscript(transcript(examples.phantom, "fr"));
    expect(aligned.segments.map((segment) => segment.text).join(" ")).toBe(examples.phantom);
    expect(aligned.segments.every((segment) => segment.splitDiagnostics?.grammarPenalty === 0)).toBe(true);
  });
});
