import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
const build = vi.hoisted(() => ({ IS_TEST_BUILD: true, BUILD_VERSION: "1.5.0" }));
vi.mock("./build-info", () => build);
import { saveCaptionDiagnostic, downloadCaptionDiagnostics } from "./caption-diagnostics";
import { alignTranslatedParts, parseTranslationResponse } from "./transcript-translation";

const input = {
  context: { videoId: "video-1", providerId: "example", modelId: "test-model" }, targetLanguage: "zh-CN",
  transcript: { languageCode: "en", isAutoGenerated: true, segments: [
    { start: 0, duration: 1, text: "Before." }, { start: 2, duration: 2, text: "Target." },
  ] },
  chunk: { id: 1, targetStart: 1, targetEnd: 1, contextStart: 0, contextEnd: 1 },
  attempts: [{ attempt: 1, protocol: "source-excerpts" as const,
    raw: '{"segments":[{"source":"Changed.","translation":"译文"}]}', code: "source", reason: "source mismatch" }],
  outcome: "failed" as const,
};

let store: Record<string, any>;
beforeEach(() => {
  build.IS_TEST_BUILD = true;
  store = {};
  vi.stubGlobal("chrome", { storage: { local: {
    get: vi.fn(async (key: string) => ({ [key]: store[key] })),
    set: vi.fn(async (value: object) => { Object.assign(store, structuredClone(value)); }),
  } } });
});
afterEach(() => { vi.unstubAllGlobals(); vi.useRealTimers(); });

describe("local caption diagnostics", () => {
  it("saves a target-only snapshot that replays source matching without a model call", async () => {
    await saveCaptionDiagnostic(input);
    const record = store["vas-caption-diagnostics"][0];
    expect(record.context).toEqual(input.context);
    expect(record.transcript.segments).toEqual([input.transcript.segments[1]]);
    expect(record.contextBefore).toBe("Before.");
    expect(() => alignTranslatedParts(record.transcript, record.chunk, parseTranslationResponse(record.attempts[0].raw)))
      .toThrow(/exactly/);
    expect(record).not.toHaveProperty("customInstruction");
  });
  it("bounds concurrent snapshots and removes expired entries", async () => {
    store["vas-caption-diagnostics"] = [{ timestamp: 1, context: input.context }];
    await Promise.all(Array.from({ length: 5 }, (_, index) => saveCaptionDiagnostic({ ...input,
      context: { ...input.context, videoId: `video-${index}` } })));
    expect(store["vas-caption-diagnostics"].map((item: any) => item.context.videoId)).toEqual(["video-2", "video-3", "video-4"]);
  });
  it("does not persist diagnostics in a release build or for a cancelled request", async () => {
    build.IS_TEST_BUILD = false;
    await saveCaptionDiagnostic(input);
    expect(chrome.storage.local.get).not.toHaveBeenCalled();
    build.IS_TEST_BUILD = true;
    const controller = new AbortController(); controller.abort();
    await saveCaptionDiagnostic(input, controller.signal);
    expect(chrome.storage.local.get).not.toHaveBeenCalled();
  });
  it("does not write a request cancelled while reading storage", async () => {
    const controller = new AbortController();
    vi.mocked(chrome.storage.local.get).mockImplementationOnce(async () => { controller.abort(); return {}; });
    await saveCaptionDiagnostic(input, controller.signal);
    expect(chrome.storage.local.set).not.toHaveBeenCalled();
  });
  it("bounds oversized responses and source data and marks incomplete replay data", async () => {
    await saveCaptionDiagnostic({ ...input,
      transcript: { ...input.transcript, segments: [{ start: 0, duration: 1, text: "x".repeat(200_000) }] },
      chunk: { id: 0, targetStart: 0, targetEnd: 0, contextStart: 0, contextEnd: 0 },
      attempts: [{ ...input.attempts[0], raw: "x".repeat(500_000) }],
    });
    const record = store["vas-caption-diagnostics"][0];
    expect(record.sourceTruncated).toBe(true);
    expect(record.attempts[0].rawTruncated).toBe(true);
    expect(JSON.stringify(record).length).toBeLessThan(30_000);
  });
  it("does not replace the original translation failure with a storage failure", async () => {
    vi.mocked(chrome.storage.local.get).mockRejectedValueOnce(new Error("storage unavailable"));
    await expect(saveCaptionDiagnostic(input)).resolves.toBeUndefined();
  });
  it("exports only recent diagnostics for the current video", async () => {
    vi.useFakeTimers();
    await saveCaptionDiagnostic(input);
    await saveCaptionDiagnostic({ ...input, context: { ...input.context, videoId: "other-video" } });
    const anchor = { href: "", download: "", click: vi.fn(), remove: vi.fn() };
    vi.stubGlobal("document", { createElement: () => anchor, body: { append: vi.fn() } });
    let blob: Blob | undefined;
    vi.stubGlobal("URL", { createObjectURL: (value: Blob) => { blob = value; return "blob:test"; }, revokeObjectURL: vi.fn() });
    await downloadCaptionDiagnostics("video-1");
    const exported = JSON.parse(await blob!.text());
    expect(exported.records).toHaveLength(1);
    expect(exported.records[0].context.videoId).toBe("video-1");
    expect(anchor.click).toHaveBeenCalledOnce();
    expect(anchor.download).toBe("caption-diagnostics-video-1.json");
    await vi.runAllTimersAsync();
    expect(URL.revokeObjectURL).toHaveBeenCalledWith("blob:test");
  });
});
