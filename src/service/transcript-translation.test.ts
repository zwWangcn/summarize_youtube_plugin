const stream = vi.mocked(streamAIText);
function source(): Transcript {
  return prepareCaptionSource({ languageCode: "en", isAutoGenerated: true, segments: [{
    start: 0, duration: 3.5, text: "I like this camera but it costs too much.",
    timingMarkers: [
      { offset: 0, start: 0 }, { offset: 2, start: .3 }, { offset: 7, start: .6 },
      { offset: 12, start: 1 }, { offset: 19, start: 1.5 }, { offset: 23, start: 1.8 },
      { offset: 26, start: 2.1 }, { offset: 32, start: 2.5 }, { offset: 36, start: 2.8 },
    ],
  }] });
}
const parts = [
  { source: "I like this camera", translation: "我喜欢这台相机" },
  { source: "but it costs too much.", translation: "但它太贵了。" },
];
const response = JSON.stringify({ segments: parts });
function tokens(...values: string[]) { return (async function* () { for (const value of values) yield value; })(); }
function failed(error: Error) { return (async function* (): AsyncGenerator<string> { throw error; })(); }
beforeEach(() => vi.clearAllMocks());
afterEach(() => vi.useRealTimers());

describe("stable source blocks", () => {
  it("covers source events once with duration and character limits, independently of model cuts", () => {
    const cues = [0, 20, 40, 60].map((start) => ({ start, duration: 20, text: "a" }));
    expect(buildTranslationChunks(cues).map((c) => [c.targetStart, c.targetEnd])).toEqual([[0, 2], [3, 3]]);
    expect(buildTranslationChunks(cues, 30).map((c) => c.targetStart)).toEqual([0, 1, 2, 3]);
    expect(buildTranslationChunks([])).toEqual([]);
    expect(buildTranslationChunks([{ start: 0, duration: 90, text: "x".repeat(5000) }])).toHaveLength(1);
  });
  it("uses natural JSON text, separates context, and preserves literal marker-like content", () => {
    const tr = prepareCaptionSource({ languageCode: "en", isAutoGenerated: false, segments: [
      { start: 0, duration: 2, text: "before" },
      { start: 2, duration: 2, text: 'literal [1] </target> "quotes"' },
      { start: 4, duration: 2, text: "after" },
    ] });
    const chunk = { id: 0, targetStart: 1, targetEnd: 1, contextStart: 0, contextEnd: 2 };
    const prompt = JSON.parse(buildTranslationUserPrompt(tr, chunk));
    expect(prompt.target).toEqual([tr.segments[1].text]);
    expect(prompt.preserveCueBoundaries).toBe(true);
    expect(prompt.contextBefore).toBe("before");
    expect(prompt.contextAfter).toBe("after");
    expect(prompt.keepTogether).toBeUndefined();
    expect(buildTranslationSystemPrompt("zh-CN", "term rule")).toContain("term rule");
  });
});

describe("source excerpts and observed time mapping", () => {
  it("splits a single original event at observed word onsets", () => {
    const tr = source(), chunk = buildTranslationChunks(tr.segments)[0];
    const aligned = alignTranslatedParts(tr, chunk, parts);
    expect(aligned).toMatchObject([
      { chunkId: 0, cueId: 0, sourceFrom: 0, sourceTo: 18, sourceText: parts[0].source, start: 0, duration: 1.5 },
      { chunkId: 0, cueId: 1, sourceFrom: 19, sourceTo: 41, sourceText: parts[1].source, start: 1.5, duration: 2 },
    ]);
  });
  it("merges original events and records the inclusive source range", () => {
    const tr = prepareCaptionSource({ languageCode: "en", isAutoGenerated: true, segments: [
      { start: 2, duration: 1, text: "We" }, { start: 3, duration: 2, text: "agree." },
    ] });
    expect(alignTranslatedParts(tr, buildTranslationChunks(tr.segments)[0], [
      { source: "We agree.", translation: "我们同意。" },
    ])[0]).toMatchObject({ sourceStartId: 0, sourceEndId: 1, start: 2, duration: 3 });
  });
  it.each([
    ["I like camera", "but it costs too much."], // omission
    ["I like this camera!", "but it costs too much."], // punctuation rewrite
    ["I like this camera"], // incomplete
    ["but it costs too much.", "I like this camera"], // reorder
    ["I like this camera", "I like this camera", "but it costs too much."], // repeat
    ["I like this camer", "a but it costs too much."], // inside word
  ])("rejects non-covering, rewritten or untimed excerpts: %j", (...excerpts) => {
    const tr = source();
    expect(() => alignTranslatedParts(tr, buildTranslationChunks(tr.segments)[0],
      excerpts.map((text) => ({ source: text, translation: "译文" })))).toThrow(TranslationFormatError);
  });
  it("rejects semantic cuts without timing instead of interpolating", () => {
    const tr = source(); tr.segments[0].timingMarkers = undefined;
    const chunk = buildTranslationChunks(tr.segments)[0];
    expect(() => alignTranslatedParts(tr, chunk, parts)).toThrow(/timestamp/);
    expect(JSON.parse(buildTranslationUserPrompt(tr, chunk)).keepTogether).toEqual([tr.segments[0].text]);
    expect(alignTranslatedParts(tr, chunk, [{ source: tr.segments[0].text, translation: "译文" }])).toHaveLength(1);
  });
  it("preserves real event gaps and rejects backwards onsets", () => {
    const tr = prepareCaptionSource({ languageCode: "en", isAutoGenerated: true, segments: [
      { start: 0, duration: 1, text: "Yes." }, { start: 3, duration: 1, text: "No." },
    ] });
    const chunk = buildTranslationChunks(tr.segments)[0];
    const result = alignTranslatedParts(tr, chunk, [{ source: "Yes.", translation: "是。" }, { source: "No.", translation: "否。" }]);
    expect(result.map((s) => [s.start, s.duration])).toEqual([[0, 1], [3, 1]]);
    const bad = source(); bad.segments[0].timingMarkers![4].start = 0;
    expect(() => alignTranslatedParts(bad, buildTranslationChunks(bad.segments)[0], parts)).toThrow(/timing/);
  });
  it("allows repeated words only by consuming the current prefix", () => {
    const tr = prepareCaptionSource({ languageCode: "en", isAutoGenerated: true, segments: [
      { start: 0, duration: 1, text: "go go", timingMarkers: [{ offset: 3, start: .5 }] },
    ] });
    expect(alignTranslatedParts(tr, buildTranslationChunks(tr.segments)[0], [
      { source: "go", translation: "走" }, { source: "go", translation: "走" },
    ]).map((s) => s.start)).toEqual([0, .5]);
  });
  it("maps CJK and UTF-16 offsets without asking the model to count characters", () => {
    const tr = prepareCaptionSource({ languageCode: "zh", isAutoGenerated: true, segments: [
      { start: 0, duration: 4, text: "你好😀世界。再见。", timingMarkers: [{ offset: 7, start: 2 }] },
    ] });
    expect(alignTranslatedParts(tr, buildTranslationChunks(tr.segments)[0], [
      { source: "你好😀世界。", translation: "Hello world." }, { source: "再见。", translation: "Goodbye." },
    ]).map((s) => s.start)).toEqual([0, 2]);
  });
});

describe("combined segmentation and translation requests", () => {
  it("normally calls the model once and never publishes unvalidated partial output", async () => {
    stream.mockImplementationOnce(() => tokens(response.slice(0, 35), response.slice(35)));
    const tr = source(), progress = vi.fn();
    const result = await translateTranscriptChunk(tr, buildTranslationChunks(tr.segments)[0], "zh-CN", progress);
    expect(result.map((s) => s.text)).toEqual(parts.map((p) => p.translation));
    expect(stream).toHaveBeenCalledTimes(1);
    expect(progress.mock.calls.every(([items]) => items.length === 0)).toBe(true);
  });
  it.each([
    '{"segments":[{"source":"a","translation":"b","start":1}]}',
    '{"segments":[]}', '{"segments":[{"source":"a","translation":""}]}', 'not json',
  ])("rejects malformed or model-timed output", (raw) => expect(() => parseTranslationResponse(raw)).toThrow(TranslationFormatError));
  it("retries a source rewrite with the validation error and keeps the custom prompt", async () => {
    stream.mockImplementationOnce(() => tokens(JSON.stringify({ segments: [{ source: "Changed.", translation: "错" }] })))
      .mockImplementationOnce(() => tokens(response));
    const tr = source();
    await translateTranscriptChunk(tr, buildTranslationChunks(tr.segments)[0], "zh-CN", undefined, undefined, "term rule");
    expect(stream).toHaveBeenCalledTimes(2);
    expect(JSON.parse(stream.mock.calls[1][1]).correction).toContain("exactly");
    expect(stream.mock.calls[1][0]).toContain("term rule");
  });
  it("bounds failed format attempts without recursively translating smaller blocks", async () => {
    stream.mockImplementation(() => tokens("{}"));
    const tr = source();
    await expect(translateTranscriptChunk(tr, buildTranslationChunks(tr.segments)[0], "zh-CN")).rejects.toThrow(TranslationFormatError);
    expect(stream).toHaveBeenCalledTimes(3);
  });
  it("restarts a truncated network response without committing its prefix", async () => {
    vi.useFakeTimers();
    stream.mockImplementationOnce(() => (async function* () { yield response.slice(0, 60); throw new TypeError("Failed to fetch"); })())
      .mockImplementationOnce(() => tokens(response));
    const tr = source();
    const pending = translateTranscriptChunk(tr, buildTranslationChunks(tr.segments)[0], "zh-CN");
    await vi.runAllTimersAsync();
    expect(await pending).toHaveLength(2);
    expect(stream).toHaveBeenCalledTimes(2);
  });
  it("does not retry a permanent provider error", async () => {
    stream.mockImplementationOnce(() => failed(new Error("Invalid API key")));
    const tr = source();
    await expect(translateTranscriptChunk(tr, buildTranslationChunks(tr.segments)[0], "zh-CN")).rejects.toThrow("Invalid API key");
    expect(stream).toHaveBeenCalledTimes(1);
  });
  it("honors cancellation even if a provider delivers late output", async () => {
    const controller = new AbortController();
    stream.mockImplementationOnce(() => (async function* () { controller.abort(); yield response; })());
    const tr = source();
    await expect(translateTranscriptChunk(tr, buildTranslationChunks(tr.segments)[0], "zh-CN", undefined, controller.signal))
      .rejects.toMatchObject({ name: "AbortError" });
  });
});

describe("uploaded subtitle tracks", () => {
  function uploaded(): Transcript {
    return prepareCaptionSource({ languageCode: "en", isAutoGenerated: false, segments: [
      { start: 1, duration: 5, text: "I like\nthis camera.", timingMarkers: [{ offset: 7, start: 2 }] },
      { start: 3, duration: 2, text: "But it costs too much." },
    ] });
  }

  it("preserves original cues, multiline text, overlapping times and gaps exactly", () => {
    const tr = uploaded();
    const result = alignTranslatedParts(tr, buildTranslationChunks(tr.segments)[0], [
      { source: tr.segments[0].text, translation: "我喜欢这台相机。" },
      { source: tr.segments[1].text, translation: "但它太贵了。" },
    ]);
    expect(result.map((segment) => [segment.sourceText, segment.start, segment.duration]))
      .toEqual(tr.segments.map((segment) => [segment.text, segment.start, segment.duration]));
    expect(result.map((segment) => segment.sourceStartId)).toEqual([0, 1]);
  });

  it("rejects merging, splitting, skipping and reordering uploaded cues", () => {
    const tr = uploaded(), chunk = buildTranslationChunks(tr.segments)[0];
    for (const excerpts of [
      [tr.segments.map((segment) => segment.text).join(" ")],
      ["I like", "this camera.", tr.segments[1].text],
      [tr.segments[0].text],
      [tr.segments[1].text, tr.segments[0].text],
    ]) {
      expect(() => alignTranslatedParts(tr, chunk, excerpts.map((text) => ({ source: text, translation: "译文" }))))
        .toThrow(/original boundaries/);
    }
  });

  it("preserves long uploaded captions even when fine timing would permit recutting", () => {
    const tr = source(); tr.isAutoGenerated = false; tr.segments[0].duration = 30;
    expect(alignTranslatedParts(tr, buildTranslationChunks(tr.segments)[0], [
      { source: tr.segments[0].text, translation: "译文" },
    ])[0]).toMatchObject({ start: 0, duration: 30 });
    expect(() => alignTranslatedParts(tr, buildTranslationChunks(tr.segments)[0], parts)).toThrow(/original boundaries/);
  });

  it("sends uploaded caption strings as a target array and only asks for translation", async () => {
    const tr = uploaded(), chunk = buildTranslationChunks(tr.segments)[0];
    const result = tr.segments.map((segment) => ({ source: segment.text, translation: "译文" }));
    stream.mockImplementationOnce(() => tokens(JSON.stringify({ segments: result })));
    expect(await translateTranscriptChunk(tr, chunk, "zh-CN")).toHaveLength(2);
    expect(stream).toHaveBeenCalledTimes(1);
    const [system, user] = stream.mock.calls[0];
    expect(system).toContain("Never merge, split, skip, duplicate or reorder captions");
    expect(system).not.toContain("You may merge");
    expect(JSON.parse(user)).toMatchObject({ preserveCueBoundaries: true, target: tr.segments.map((segment) => segment.text) });
  });

  it("repairs a model's attempted recut instead of accepting changed upload timing", async () => {
    const tr = source(); tr.isAutoGenerated = false;
    stream.mockImplementationOnce(() => tokens(response))
      .mockImplementationOnce(() => tokens(JSON.stringify({ segments: [{ source: tr.segments[0].text, translation: "译文" }] })));
    const result = await translateTranscriptChunk(tr, buildTranslationChunks(tr.segments)[0], "zh-CN");
    expect(stream).toHaveBeenCalledTimes(2);
    expect(result).toHaveLength(1);
    expect(result[0]).toMatchObject({ start: 0, duration: 3.5, sourceText: tr.segments[0].text });
    expect(JSON.parse(stream.mock.calls[1][1]).correction).toContain("original boundaries");
  });
});


describe("real-world caption validation regressions", () => {
  it("accepts line wrapping and repeated whitespace while retaining exact source coordinates", () => {
    const tr = source();
    const text = "I like\nthis camera   but it costs too much.";
    tr.segments[0].text = text;
    tr.segments[0].timingMarkers = [{ offset: 0, start: 0 }, { offset: text.indexOf("but"), start: 1.5 }];
    const aligned = alignTranslatedParts(tr, buildTranslationChunks(tr.segments)[0], [
      { source: " I like this camera ", translation: "我喜欢这台相机" },
      { source: "but  it costs too much.", translation: "但它太贵了。" },
    ]);
    expect(aligned[0]).toMatchObject({ sourceText: "I like\nthis camera", start: 0, duration: 1.5 });
    expect(aligned[1]).toMatchObject({ sourceFrom: text.indexOf("but"), start: 1.5, duration: 2 });
  });

  it("keeps uploaded caption line breaks even if the model returns spaces", () => {
    const tr = source(); tr.isAutoGenerated = false;
    tr.segments[0].text = "I like\nthis camera.";
    const [aligned] = alignTranslatedParts(tr, buildTranslationChunks(tr.segments)[0], [
      { source: "I like this camera.", translation: "我喜欢这台相机。" },
    ]);
    expect(aligned.sourceText).toBe("I like\nthis camera.");
    expect(aligned.start).toBe(0);
    expect(aligned.duration).toBe(3.5);
  });

  it("rejects changed words and punctuation even with whitespace tolerance", () => {
    const tr = source(), chunk = buildTranslationChunks(tr.segments)[0];
    for (const wrong of ["Ilike this camera but it costs too much.", "I like this camera but it costs too much!", "I like this camera it costs too much."]) {
      expect(() => alignTranslatedParts(tr, chunk, [{ source: wrong, translation: "译文" }]))
        .toThrow(TranslationFormatError);
      try { alignTranslatedParts(tr, chunk, [{ source: wrong, translation: "译文" }]); }
      catch (error) { expect(error).toMatchObject({ code: "source" }); }
    }
  });

  it("rejects a 12-second merged caption and accepts short clauses at the same observed times", () => {
    const words = Array(60).fill("word");
    const tr = prepareCaptionSource({ languageCode: "en", isAutoGenerated: true, segments: [{
      text: words.join(" "), start: 0, duration: 12,
      timingMarkers: words.map((_, index) => ({ offset: index * 5, start: index * .2 })),
    }] });
    const chunk = buildTranslationChunks(tr.segments)[0];
    const long = alignTranslatedParts(tr, chunk, [{ source: tr.segments[0].text, translation: "很长的译文" }]);
    expect(captionReadabilityIssue(tr, chunk, long)).toContain("shorter clauses");
    const short = Array.from({ length: 5 }, () => ({ source: words.slice(0, 12).join(" "), translation: "这是一个较短的字幕片段" }));
    const aligned = alignTranslatedParts(tr, chunk, short);
    expect(aligned).toHaveLength(5);
    expect(aligned.every((segment) => segment.duration < 3)).toBe(true);
  });

  it("preserves a coarse untimed span instead of inventing cuts just to satisfy length", () => {
    const tr = source(); tr.segments[0].duration = 30; tr.segments[0].timingMarkers = [];
    const result = alignTranslatedParts(tr, buildTranslationChunks(tr.segments)[0], [{ source: tr.segments[0].text, translation: "译文" }]);
    expect(result[0].duration).toBe(30);
  });

  it("reports timestamp validation separately from malformed JSON", async () => {
    const tr = source(); tr.segments[0].timingMarkers = [];
    const debug = vi.spyOn(console, "debug").mockImplementation(() => {});
    stream.mockImplementationOnce(() => tokens(response)).mockImplementationOnce(() => tokens(response))
      .mockImplementationOnce(() => tokens('{"translations":[{"cueId":0,"translation":"我喜欢这台相机，但它太贵了。"}]}'));
    const result = await translateTranscriptChunk(tr, buildTranslationChunks(tr.segments)[0], "zh-CN");
    expect(result).toMatchObject([{ start: 0, duration: 3.5, sourceText: tr.segments[0].text }]);
    expect(debug).toHaveBeenCalledWith("[vas] Caption validation rejected", expect.objectContaining({ code: "timing" }));
    debug.mockRestore();
  });
});

describe("fixed-caption recovery within the shared retry budget", () => {
  it("recovers repeated source mismatches without model source text or guessed timing", async () => {
    const tr = prepareCaptionSource({ languageCode: "en", isAutoGenerated: true, segments: [
      { start: 0, duration: 1, text: "I agree." }, { start: 3, duration: 2, text: "I agree." },
    ] });
    const chunk = buildTranslationChunks(tr.segments)[0];
    stream.mockImplementationOnce(() => tokens('{"segments":[{"source":"I agree.","translation":"同意"}]}'))
      .mockImplementationOnce(() => tokens('{"segments":[{"source":"I agree.","translation":"同意"}]}'))
      .mockImplementationOnce(() => tokens('{"translations":[{"cueId":0,"translation":"同意。"},{"cueId":1,"translation":"我同意。"}]}'));
    const result = await translateTranscriptChunk(tr, chunk, "zh-CN", undefined, undefined, "term rule");
    expect(stream).toHaveBeenCalledTimes(3);
    expect(stream.mock.calls[2][0]).toContain("term rule");
    expect(stream.mock.calls[2][0]).not.toContain("EXACT contiguous");
    expect(JSON.parse(stream.mock.calls[2][1]).target).toEqual([
      { cueId: 0, source: "I agree." }, { cueId: 1, source: "I agree." },
    ]);
    expect(result.map((item) => [item.sourceText, item.start, item.duration, item.text])).toEqual([
      ["I agree.", 0, 1, "同意。"], ["I agree.", 3, 2, "我同意。"],
    ]);
    // Persisted fallback uses exactly the same restoration path as ordinary results.
    expect(alignTranslatedParts(tr, chunk, result.map((item) => ({ source: item.sourceText, translation: item.text })))).toEqual(result);
  });
  it.each([
    '{"translations":[{"cueId":1,"translation":"译文"},{"cueId":0,"translation":"译文"}]}',
    '{"translations":[{"cueId":0,"translation":"译文"},{"cueId":0,"translation":"译文"}]}',
    '{"translations":[{"cueId":0,"translation":"译文"}]}',
    '{"translations":[{"cueId":0,"translation":"译文","start":0},{"cueId":1,"translation":"译文"}]}',
    '{"translations":[{"cueId":0,"translation":""},{"cueId":1,"translation":"译文"}]}',
  ])("rejects reordered, duplicate, missing, empty or model-timed fallback output", (raw) => {
    expect(() => parseFixedTranslationResponse(raw, [{ cueId: 0, source: "first" }, { cueId: 1, source: "second" }])).toThrow(TranslationFormatError);
  });
  it("groups event edges without increasing onsets and retains real pauses", () => {
    const tr = prepareCaptionSource({ languageCode: "en", isAutoGenerated: true, segments: [
      { start: 0, duration: 0, text: "Hello" }, { start: 0, duration: 1, text: ", world." },
      { start: 3, duration: 1, text: "Again." }, { start: 4, duration: 0, text: "Bye." },
    ] });
    const chunk = buildTranslationChunks(tr.segments)[0];
    const units = buildFixedCaptionUnits(tr, chunk);
    expect(units).toEqual([{ cueId: 0, source: "Hello, world." }, { cueId: 1, source: "Again. Bye." }]);
    expect(alignTranslatedParts(tr, chunk, units.map((unit) => ({ source: unit.source, translation: "译文" })))
      .map((item) => [item.start, item.duration])).toEqual([[0, 1], [3, 1]]);
  });
  it("preserves uploaded boundaries, line breaks, overlapping times and source coordinates in fallback", async () => {
    const tr = prepareCaptionSource({ languageCode: "en", isAutoGenerated: false, segments: [
      { start: 0, duration: 5, text: "Before" }, { start: 3, duration: 4, text: "Hello\nworld." },
      { start: 6, duration: 3, text: "Again." },
    ] });
    const chunk = { id: 5, targetStart: 1, targetEnd: 2, contextStart: 0, contextEnd: 2 };
    stream.mockImplementationOnce(() => tokens("{}")) .mockImplementationOnce(() => tokens("{}"))
      .mockImplementationOnce(() => tokens('{"translations":[{"cueId":0,"translation":"你好。"},{"cueId":1,"translation":"再来。"}]}'));
    const result = await translateTranscriptChunk(tr, chunk, "zh-CN");
    expect(result).toMatchObject([
      { sourceText: "Hello\nworld.", start: 3, duration: 4, sourceStartId: 1 },
      { sourceText: "Again.", start: 6, duration: 3, sourceStartId: 2 },
    ]);
    expect(JSON.parse(stream.mock.calls[2][1]).contextBefore).toBe("Before");
  });
  it("normalizes quotation styles without changing the source shown or its word onsets", async () => {
    const tr = prepareCaptionSource({ languageCode: "en", isAutoGenerated: true, segments: [
      { start: 0, duration: 4, text: "It’s good. Again.", timingMarkers: [{ offset: 11, start: 2 }] },
    ] });
    stream.mockImplementationOnce(() => tokens(JSON.stringify({ segments: [
      { source: "It's good.", translation: "很好。" }, { source: "Again.", translation: "再来。" },
    ] })));
    const result = await translateTranscriptChunk(tr, buildTranslationChunks(tr.segments)[0], "zh-CN");
    expect(result.map((item) => [item.sourceText, item.start])).toEqual([["It’s good.", 0], ["Again.", 2]]);
    expect(stream).toHaveBeenCalledTimes(1);
  });
  it("does not publish a fixed-caption response cancelled during the final attempt", async () => {
    const tr = source(), controller = new AbortController();
    stream.mockImplementationOnce(() => tokens("{}")) .mockImplementationOnce(() => tokens("{}"))
      .mockImplementationOnce(() => (async function* () {
        controller.abort(); yield '{"translations":[{"cueId":0,"translation":"译文"}]}';
      })());
    await expect(translateTranscriptChunk(tr, buildTranslationChunks(tr.segments)[0], "zh-CN", undefined, controller.signal))
      .rejects.toMatchObject({ name: "AbortError" });
    expect(stream).toHaveBeenCalledTimes(3);
  });
});


describe("readability never invalidates a structurally correct translation", () => {
  function longSource(): Transcript {
    const words = Array(60).fill("word");
    return prepareCaptionSource({ languageCode: "en", isAutoGenerated: true, segments: [{
      text: words.join(" "), start: 0, duration: 12,
      timingMarkers: words.map((_, index) => ({ offset: index * 5, start: index * .2 })),
    }] });
  }

  it("accepts the reported short phrase with a long display lifetime and trailing silence", async () => {
    const text = "looking almost too good to be true,";
    const words = text.split(" "); let offset = 0;
    const tr = prepareCaptionSource({ languageCode: "en", isAutoGenerated: true, segments: [{
      text, start: 0, duration: 30, timingMarkers: words.map((word, index) => {
        const marker = { offset, start: index * .3 }; offset += word.length + 1; return marker;
      }),
    }] });
    const chunk = buildTranslationChunks(tr.segments)[0];
    stream.mockImplementationOnce(() => tokens(JSON.stringify({ segments: [{ source: text, translation: "好得令人难以置信，" }] })));
    const result = await translateTranscriptChunk(tr, chunk, "zh-CN");
    expect(result[0]).toMatchObject({ sourceText: text, duration: 30 });
    expect(captionReadabilityIssue(tr, chunk, result)).toBeNull();
    expect(stream).toHaveBeenCalledTimes(1);
  });

  it("tries one shorter-clause repair, then accepts a valid result even if length remains high", async () => {
    const tr = longSource(), chunk = buildTranslationChunks(tr.segments)[0];
    const output = JSON.stringify({ segments: [{ source: tr.segments[0].text, translation: "译文" }] });
    stream.mockImplementation(() => tokens(output));
    const result = await translateTranscriptChunk(tr, chunk, "zh-CN");
    expect(result).toHaveLength(1);
    expect(stream).toHaveBeenCalledTimes(2);
  });

  it("keeps the last validated translation when a readability repair corrupts the source", async () => {
    const tr = longSource(), chunk = buildTranslationChunks(tr.segments)[0];
    stream.mockImplementationOnce(() => tokens(JSON.stringify({ segments: [{ source: tr.segments[0].text, translation: "有效译文" }] })))
      .mockImplementationOnce(() => tokens(JSON.stringify({ segments: [{ source: "changed source", translation: "错误修正" }] })));
    const result = await translateTranscriptChunk(tr, chunk, "zh-CN");
    expect(result[0].text).toBe("有效译文");
    expect(result[0].sourceText).toBe(tr.segments[0].text);
    expect(stream).toHaveBeenCalledTimes(2);
  });

  it("keeps a valid translation after a readability repair network failure", async () => {
    const tr = longSource(), chunk = buildTranslationChunks(tr.segments)[0];
    stream.mockImplementationOnce(() => tokens(JSON.stringify({ segments: [{ source: tr.segments[0].text, translation: "有效译文" }] })))
      .mockImplementationOnce(() => failed(new TypeError("Failed to fetch")));
    expect((await translateTranscriptChunk(tr, chunk, "zh-CN"))[0].text).toBe("有效译文");
  });

  it("still respects cancellation instead of committing the quality fallback", async () => {
    const tr = longSource(), chunk = buildTranslationChunks(tr.segments)[0], controller = new AbortController();
    stream.mockImplementationOnce(() => tokens(JSON.stringify({ segments: [{ source: tr.segments[0].text, translation: "有效译文" }] })))
      .mockImplementationOnce(() => (async function* () { controller.abort(); yield "{}"; })());
    await expect(translateTranscriptChunk(tr, chunk, "zh-CN", undefined, controller.signal)).rejects.toMatchObject({ name: "AbortError" });
  });
});
