// Store listing image harness: renders the extension's real Panel and
// BilingualSubtitleOverlay over a captured video frame, plus poster layouts.
// Usage: index.html?shot=<poster|summary|bilingual|chat|transcript|tile|marquee>&lang=<zh-CN|zh-TW|en|ja|ko>

import { Panel } from "../../src/content/ui/panel";
import { BilingualSubtitleOverlay } from "../../src/content/ui/bilingual-overlay";
import { renderMarkdown, renderStreaming, renderTranscriptSections } from "../../src/content/ui/renderer";
import { activateUiLanguage, t } from "../../src/utils/i18n";
import type { Transcript } from "../../src/content/transcript";
import type { TranslationChunk, TranslatedSegment } from "../../src/service/transcript-translation";
import {
  COPY, PROVIDERS, SOURCE_REAL_ESTATE, SOURCE_TREASURY, TRANSCRIPT_SOURCE, VIDEO_TITLE,
  type Copy, type Lang,
} from "./content";
import frame951 from "./frames/frame-951.png";
import frame2950 from "./frames/frame-2950.png";
import frame1800 from "./frames/frame-1800.png";
import frame420 from "./frames/frame-420.png";
import appIcon from "../../assets/icons/icon.svg";

const params = new URLSearchParams(location.search);
const shot = params.get("shot") ?? "poster";
const lang = (params.get("lang") ?? "zh-CN") as Lang;
const copy: Copy = COPY[lang];

const FONT_STACK = `"Inter", ${copy.font}, "Noto Sans SC", "Segoe UI", sans-serif`;
const ICONS: Record<string, string> = {
  summary: '<path d="M4 6h16M4 12h11M4 18h14"/>',
  subtitles: '<rect x="3" y="5" width="18" height="14" rx="3"/><path d="M7 12h4M13 12h4M7 15.5h10"/>',
  chat: '<path d="M20.5 11.5a8.5 8.5 0 0 1-12.4 7.6L3.5 20.5l1.4-4.4A8.5 8.5 0 1 1 20.5 11.5z"/><path d="M9.6 9.4a2.5 2.5 0 0 1 4.8.9c0 1.7-2.4 2.2-2.4 3.4M12 16.4h.01"/>',
  translate: '<path d="M4 5h8M8 3v2M5.5 9.5c1.4 2.6 3.6 4.4 6.5 5.5M11 5c-.9 4-3.4 7.4-7 9"/><path d="M13 21l4-9 4 9M14.4 18h5.2"/>',
  check: '<path d="M5 12.5l4.2 4.2L19 7"/>',
};
const icon = (name: string, size = 20) =>
  `<svg width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${ICONS[name]}</svg>`;

// ---------------------------------------------------------------------------
// Real components
// ---------------------------------------------------------------------------
function mountPanel(frame: HTMLElement): Panel {
  const panel = new Panel({
    onSummarize: () => {}, onTranscript: () => {}, onClose: () => {},
    onTranslateCurrent: () => {}, onTranslateAll: () => {}, onAsk: () => {},
    onAskSubmit: () => {}, onAskNewChat: () => {},
  } as never);
  panel.injectPanel(frame);
  const host = frame.querySelector<HTMLElement>("#vas-root")!;
  // Match the poster typography (and give ja/ko/zh-TW their own CJK glyphs).
  host.style.setProperty("--vas-font-sans", FONT_STACK);
  const fix = document.createElement("style");
  fix.textContent = `.vas-panel{top:0!important;right:0!important;bottom:0;left:0;width:auto!important;max-height:none!important;animation:none!important}
    .vas-resize-handle{display:none}`;
  host.shadowRoot!.appendChild(fix);
  panel.setAIAvailable(true, "DeepSeek");
  panel.setTitle(VIDEO_TITLE);
  panel.open();
  return panel;
}

function mountOverlay(player: HTMLElement, source: string, translation: string, small = false): void {
  const overlay = new BilingualSubtitleOverlay(player);
  overlay.setSourceReady(true);
  overlay.setCue({ sourceText: source, translationText: translation });
  const host = player.querySelector<HTMLElement>("#vas-bilingual-overlay")!;
  host.style.setProperty("font-family", FONT_STACK);
  if (small) {
    host.style.setProperty("--vas-source-font-size", "13px");
    host.style.setProperty("--vas-translation-font-size", "15px");
  }
}

function showSummary(panel: Panel): void {
  panel.setContent(renderMarkdown(copy.summaryMd));
  panel.setMode("summary");
}

function showChat(panel: Panel): void {
  panel.setMode("chat");
  const content = panel.getContentElement();
  content.replaceChildren();
  for (const turn of copy.chat) {
    const wrapper = document.createElement("div");
    wrapper.className = "vas-chat-turn";
    const question = document.createElement("div");
    question.className = "vas-chat-question";
    question.textContent = turn.q;
    const answer = document.createElement("div");
    answer.className = "vas-chat-answer";
    renderStreaming(answer, turn.a);
    wrapper.append(question, answer);
    content.appendChild(wrapper);
  }
  content.scrollTop = 0;
}

function showTranscript(panel: Panel): void {
  panel.setTranslationAvailable(true);
  const segments = TRANSCRIPT_SOURCE.map(([start, duration, text]) => ({ start, duration, text }));
  const transcript: Transcript = { languageCode: "en", isAutoGenerated: true, segments };
  const chunks: TranslationChunk[] = Array.from({ length: 66 }, (_, id) => ({
    id, targetStart: 0, targetEnd: 0, contextStart: 0, contextEnd: 0,
  }));
  chunks[16] = { id: 16, targetStart: 0, targetEnd: 5, contextStart: 0, contextEnd: 9 };
  chunks[17] = { id: 17, targetStart: 6, targetEnd: 9, contextStart: 0, contextEnd: 9 };
  const aligned = (from: number, to: number) => copy.transcript.slice(from, to + 1).map(([start, text], i) => ({
    start, text, sourceText: segments[from + i].text,
  }) as unknown as TranslatedSegment);
  panel.setMode("transcript");
  panel.setTranscriptView("translation");
  panel.setTranscriptRange(t("sectionRange", ["17", "66", "14:43", "15:36"]));
  panel.setCurrentSectionTranslated(true);
  renderTranscriptSections(panel.getContentElement(), transcript, {
    chunks, loadedStart: 16, loadedEnd: 17, activeChunkId: 16, view: "translation",
    translations: { 16: aligned(0, 5), 17: aligned(6, 9) }, withTimestamps: true,
  });
}

// ---------------------------------------------------------------------------
// Layouts
// ---------------------------------------------------------------------------
const appIconImg = (size: number, cls = "app-icon") => `<img class="${cls}" src="${appIcon}" width="${size}" height="${size}" alt="">`;
const brandRow = (size = 40) => `
  <div class="brand">${appIconImg(size)}<span>${copy.brand}</span></div>`;

function headline(pair: [string, string]): string {
  return `<div class="headline">${brandRow(34)}<h1>${pair[0]}</h1><p>${pair[1]}</p></div>`;
}

function videoScene(stage: HTMLElement, kind: "summary" | "chat" | "transcript" | "bilingual"): void {
  const withPanel = kind !== "bilingual";
  const frame = { summary: frame951, chat: frame1800, transcript: frame420, bilingual: frame2950 }[kind];
  stage.innerHTML = `
    <div class="scene" style="background-image:url(${frame});background-size:auto ${withPanel ? 900 : 800}px;background-position:${withPanel ? "-320px -40px" : "-142px 0"}">
      <div class="player" style="width:${withPanel ? 820 : 1280}px"></div>
      <div class="shade"></div>
      ${headline(copy.shots[kind])}
      ${kind === "bilingual" ? `<div class="chip">${icon("subtitles", 18)}<span>${copy.learningMode}</span></div>` : ""}
      ${withPanel ? '<div class="panel-frame"></div>' : ""}
    </div>`;
  const player = stage.querySelector<HTMLElement>(".player")!;
  if (kind === "bilingual") mountOverlay(player, SOURCE_REAL_ESTATE, copy.cueRealEstate);
  else mountOverlay(player, SOURCE_TREASURY, copy.cueTreasury);
  if (!withPanel) return;
  const panel = mountPanel(stage.querySelector<HTMLElement>(".panel-frame")!);
  if (kind === "summary") showSummary(panel);
  if (kind === "chat") showChat(panel);
  if (kind === "transcript") showTranscript(panel);
}

function poster(stage: HTMLElement): void {
  const p = copy.poster;
  const [line1, ...rest] = p.headline.split("\n");
  stage.innerHTML = `
    <div class="poster">
      <div class="glow"></div>
      <div class="left">
        ${brandRow(44)}
        <div class="kicker">${p.kicker}</div>
        <h1 class="big">${line1}<br><em>${rest.join("<br>")}</em></h1>
        <p class="sub">${p.sub}</p>
        <ul class="features">
          ${p.features.map((f, i) => `<li><span class="ficon">${icon(["summary", "subtitles", "chat", "translate"][i], 20)}</span>
            <div><b>${f.title}</b><small>${f.desc}</small></div></li>`).join("")}
        </ul>
        <div class="trust">${p.trust.map((x) => `<span>${icon("check", 15)}${x}</span>`).join("")}</div>
        <div class="providers"><i>${p.providersLabel}</i>${PROVIDERS.map((x) => `<span>${x}</span>`).join("")}</div>
      </div>
      <div class="right">
        <div class="video"><div class="player"></div><div class="progress"><b></b></div></div>
        <div class="panel-frame small"></div>
        ${chatCard()}
      </div>
    </div>`;
  mountOverlay(stage.querySelector<HTMLElement>(".video .player")!, SOURCE_TREASURY, copy.cueTreasury, true);
  showSummary(mountPanel(stage.querySelector<HTMLElement>(".panel-frame")!));
}

/** Compact Q&A card in the panel's visual language (first chat turn). */
function chatCard(): string {
  const turn = copy.chat[0];
  const answer = turn.a.split("\n\n")[0].replace(/\*\*(.+?)\*\*/g, "<b>$1</b>");
  const cite = turn.a.match(/\[(\d\d:\d\d)\]/g)?.slice(0, 2) ?? [];
  return `<div class="chat-card">
      <div class="chat-tab">${icon("chat", 14)}<span>${t("askVideo")}</span></div>
      <div class="q">${turn.q}</div>
      <div class="a">${answer}</div>
      <div class="cites">${cite.map((c) => `<span>${c.slice(1, -1)}</span>`).join("")}</div>
    </div>`;
}

function marquee(stage: HTMLElement): void {
  stage.innerHTML = `
    <div class="poster marquee">
      <div class="glow"></div>
      <div class="left">
        ${brandRow(44)}
        <h1 class="big">${copy.poster.headline.replace("\n", "<br><em>")}</em></h1>
        <div class="tags">${copy.tile.tags.map((x) => `<span>${x}</span>`).join("")}</div>
      </div>
      <div class="right">
        <div class="video"><div class="player"></div><div class="progress"><b></b></div></div>
        ${chatCard()}
      </div>
    </div>`;
  mountOverlay(stage.querySelector<HTMLElement>(".video .player")!, SOURCE_TREASURY, copy.cueTreasury, true);
}

function tile(stage: HTMLElement): void {
  stage.innerHTML = `
    <div class="tile">
      <div class="glow"></div>
      ${appIconImg(96, "tile-icon")}
      <div class="tile-text">
        <h1>${copy.tile.title.replace(/^YouTube /, "<span>YouTube</span><br>")}</h1>
        <div class="tags">${copy.tile.tags.map((x) => `<span>${x}</span>`).join("")}</div>
      </div>
    </div>`;
}

const SIZES: Record<string, [number, number]> = { tile: [440, 280], marquee: [1400, 560] };

async function main(): Promise<void> {
  document.documentElement.lang = copy.htmlLang;
  document.documentElement.style.setProperty("--font", FONT_STACK);
  await activateUiLanguage(lang);
  const stage = document.getElementById("stage")!;
  const [w, h] = SIZES[shot] ?? [1280, 800];
  stage.style.width = `${w}px`;
  stage.style.height = `${h}px`;
  if (shot === "poster") poster(stage);
  else if (shot === "marquee") marquee(stage);
  else if (shot === "tile") tile(stage);
  else videoScene(stage, shot as "summary" | "chat" | "transcript" | "bilingual");
  await document.fonts.ready;
  await new Promise((r) => setTimeout(r, 300));
  document.title = "READY";
}

void main();
